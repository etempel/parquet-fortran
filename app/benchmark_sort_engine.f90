! Author: Elmo Tempel (elmo.tempel@ut.ee)
!===========================================
!
!> Baseline and regression harness for the pure-Fortran sort engine campaign
!! (`feature_sort.md`; run sheet `feature_benchmark_sort.md`).
!!
!! **What this is for.** `feature_sort.md` proposes replacing the C++ sort engine that
!! `parquet_sorting` calls with a Fortran one. Its Stage 0 requires a committed baseline taken on
!! the *current* engine, across every key family and input shape the engine was built for — because
!! without one, every later figure is a number with nothing to compare against, and the campaign
!! can only answer "is the new one fast?" rather than "did we lose anything?".
!!
!! **The baseline arm is the shipped `pf_argsort`, not any external sort.** An earlier one-off
!! comparison used qfeet's `qsort_index`; that is retired. qfeet is unstable, NaN-intolerant and
!! null-unaware, so it is not a substitutable implementation of the same operation and cannot
!! answer a regression question. Every figure here is a ratio against this library at the commit
!! under test.
!!
!! **The data is generated by an xorshift64 PRNG, NOT by `random_number`.** That is deliberate and
!! load-bearing for this campaign: `random_number` produces a *different sequence* under gfortran
!! and under ifx, so a gfortran-versus-ifx comparison of the same nominal arm would be comparing
!! two different inputs. The generator here uses only `ieor`/`ishft`, so it is bit-identical on
!! every compiler and every architecture, and it cannot overflow (integer overflow is not defined
!! behaviour in Fortran, so a multiply-based LCG would be a latent trap).
!!
!! Rules this program follows, each because breaking it produced a wrong number somewhere in this
!! repository before (CLAUDE.md, "Manual (never-`fpm test`) large-scale/benchmark tools"):
!!
!!   * **Every input and every destination is written through once before any timing.** A freshly
!!     allocated array pays first-touch page faults on its first pass and never again, which is
!!     strong enough to reverse a comparison purely by running order.
!!   * **Every figure is the best of several rounds**, never a single measurement.
!!   * **Every result is verified before its timing is accepted** — the permutation must be a
!!     permutation, and (where the arm has no nulls and no NaNs) it must actually sort the input.
!!     A fast wrong answer is the one failure mode a benchmark will happily report as a win.
!!   * **Every value read is folded into a checksum printed at the end**, so nothing is optimised
!!     away, and so a variant that changes the ANSWER as well as the timing is visible as such.
!!   * **No `mod` with a runtime divisor anywhere in a timed loop.** It compiles to a 64-bit
!!     integer division (~6 ns on x86-64) and has previously been the whole of a reported floor.
!!   * The wrapper passes `--profile release`, without which fpm applies no optimisation at all and
!!     every number here is meaningless.
!!
!! **What each arm measures.** Single-key arms call the public array API, so they are end-to-end:
!! key extraction, the `bind(C)` crossing, the sort, and the permutation copy-back. That is what a
!! user pays and what the acceptance bar in `feature_sort.md` is set on. **Multi-key arms build
!! their `pf_sort_keys` OUTSIDE the timer** and time only `pf_argsort(keys, perm)`, because
!! extraction is identical before and after the refactor and including it would only dilute the
!! signal the campaign is looking for. Both choices are stated in the printed header so a figure
!! cannot be read as the other kind.
!!
!! **`--perm=64` is not a formality.** The int32 permutation specifics allocate an `int64`
!! permutation and then narrow it into a second array (`narrow_perm`), so the int32 and int64 paths
!! differ by one full O(n) allocation and conversion pass. `feature_sort.md` §2.5 identifies that
!! as one of the buffers a Fortran engine deletes outright, so measuring both is how the campaign
!! finds out how much of the gap is marshalling rather than sorting.
!!
!! Maintainer tool, never run by `fpm test`. Drive it with tools/benchmark_sort_engine.sh.
program benchmark_sort_engine
    use parquet
    use iso_fortran_env, only : int32, int64, real32, real64, error_unit, output_unit
#ifdef _OPENMP
    use omp_lib, only : omp_get_wtime, omp_get_max_threads
#endif
    implicit none

    ! ---- configuration, all settable from the wrapper ----
    character(len=:), allocatable :: mode      !! which group of arms to run.
    character(len=:), allocatable :: families  !! comma-separated family list, or "all".
    character(len=:), allocatable :: dists     !! comma-separated distribution list, or "all".
    character(len=:), allocatable :: thread_dist
    !! the ONE distribution `--mode=threads` sweeps. Defaults to "rand", which is what every earlier
    !! report was taken with, so the default output is unchanged. It exists because the thread ladder
    !! is the only mode that can answer "does this phase parallelise", and phases that only run for a
    !! column WITH nulls or NaNs (the non-value-tier tail) are invisible under "rand".
    character(len=:), allocatable :: sizes_arg !! comma-separated row counts.
    integer :: rounds = 5                      !! rounds per figure; the best is kept.
    integer :: permkind = 32                   !! 32 or 64: which permutation kind to ask for.
    integer :: strwidth = 16                   !! declared width of a string key's elements.
    integer :: threads_hi = -1                 !! high thread count; -1 = omp_get_max_threads().
    integer(int64) :: seed_arg = 20260814_int64
    character(len=:), allocatable :: engine !! "cpp" or "fortran": which sort engine to measure.
    integer(int64) :: radix_min !! forced radix row floor; NEGATIVE leaves the shipped one in force.
    integer :: inner = 1 !! argsort repetitions INSIDE one timed region; see time_argsort.

    integer(int64), allocatable :: sizes(:)
    integer(int64) :: checksum = 0_int64
    integer :: nfig = 0                        !! figures printed, for the trailer.

    ! ---- the current data set ----
    !
    ! Held here rather than passed into the timed call, so that the argument-association cost of
    ! the measured call does not vary by family and cannot be mistaken for a sorting cost.
    integer(int32), allocatable :: vi32(:)         !! int32 key values.
    integer(int64), allocatable :: vi64(:)         !! int64 key values (also the low-cardinality arm).
    real(real32), allocatable :: vf32(:)           !! real32 key values.
    real(real64), allocatable :: vf64(:)           !! real64 key values.
    character(len=:), allocatable :: vstr(:)       !! string key values, fixed width.
    ! vvalid is passed DIRECTLY as `is_valid=vvalid`, and it must stay a VARIABLE. Passing an
    ! unallocated allocatable to an optional dummy makes that dummy absent (F2018 15.5.2.12), which
    ! is how one call site serves both the masked and unmasked arms -- but that rule is about a
    ! VARIABLE. It does not cover an unallocated allocatable FUNCTION RESULT, and a helper of that
    ! shape used to sit here. gfortran accepted it; ifx 2026.1.1 passed the dummy as PRESENT with a
    ! garbage descriptor, and the whole ifx arm of the 2026-08-14 machine B campaign aborted on its
    ! first figure with "is_valid has 140735245936080 elements" -- a stack address read as size().
    ! Do not reintroduce a function here: it is unallocated exactly when has_valid is .false.
    logical, allocatable :: vvalid(:)              !! validity mask; allocated only for a null arm.
    type(pf_sort_keys) :: mkeys                    !! the multi-key object, built outside the timer.
    integer(int32), allocatable :: perm32(:)       !! int32 permutation destination.
    integer(int64), allocatable :: perm64(:)       !! int64 permutation destination.
    real(real64), allocatable :: sf64(:)           !! a sorted real64 copy, for search/merge.
    integer(int64), allocatable :: si64(:)         !! a sorted int64 copy, for search/merge.
    logical :: has_valid = .false.                 !! .true. when this arm carries a validity mask.

    call parse_args()
    call print_header()

    select case (mode)
    case ("argsort")
        call run_argsort()
    case ("dist")
        call run_dist()
    case ("ops")
        call run_ops()
    case ("threads")
        call run_threads()
    case ("all")
        call run_argsort()
        call run_dist()
        call run_ops()
    case default
        write(error_unit,'(a)') "benchmark_sort_engine: unknown mode '"//mode//"'"
        call usage()
        error stop 2
    end select

    write(output_unit,'(a)') ""
    write(output_unit,'(a,i0,a,i0)') "# figures: ", nfig, "   checksum: ", checksum
    write(output_unit,'(a)') "# checksum is data-dependent and MUST be identical between two builds"
    write(output_unit,'(a)') "# that claim to compute the same answer -- see feature_benchmark_sort.md."

contains

    ! ================================================================================
    ! Arms
    ! ================================================================================

    !> The main sweep: one key family per row set, over the size ladder, serial and threaded.
    subroutine run_argsort()
        integer :: fi, si
        character(len=:), allocatable :: fam
        !
        call section("argsort -- one key, over the size ladder (dist=rand)")
        call table_head()
        do fi = 1, list_len(families)
            fam = list_item(families, fi)
            do si = 1, size(sizes)
                call one_argsort(fam, "rand", sizes(si), 1)
                if (thi() > 1) call one_argsort(fam, "rand", sizes(si), thi())
            end do
        end do
    end subroutine run_argsort

    !> Input SHAPE sweep at one size: the adversarial and null/NaN-bearing distributions.
    !!
    !! Held at one size deliberately -- this asks "does the shape of the input change the cost?",
    !! which needs many shapes and one n, not the other way round. `sorted`/`reverse`/`equal`/
    !! `organ` are quicksort's classical adversaries and are what decide whether an introsort's
    !! depth limit is doing its job; `null001` is at the density that produced the documented
    !! 4.6x-5.6x counting-path cliff, so it is not an arbitrary small number.
    subroutine run_dist()
        integer :: fi, di
        integer(int64) :: n
        character(len=:), allocatable :: fam, dst
        !
        n = sizes(size(sizes))
        call section("dist -- input shape at n = " // i2s(n))
        call table_head()
        do fi = 1, list_len(families)
            fam = list_item(families, fi)
            do di = 1, list_len(dists)
                dst = list_item(dists, di)
                if (.not. dist_applies(fam, dst)) cycle
                call one_argsort(fam, dst, n, 1)
                if (thi() > 1) call one_argsort(fam, dst, n, thi())
            end do
        end do
    end subroutine run_dist

    !> Thread scaling at the largest size, for each family.
    !!
    !! The counts come from the wrapper (THREAD_LIST) rather than being hard-coded, because the
    !! interesting ones are machine-specific: on a dual-socket machine, one socket, both sockets'
    !! physical cores and the SMT count are three different questions, and a scheme that stops
    !! scaling at one socket is reporting a NUMA limit rather than a thread limit.
    subroutine run_threads()
        integer :: fi, ti
        integer(int64) :: n
        integer, allocatable :: tl(:)
        character(len=:), allocatable :: fam
        !
        n = sizes(size(sizes))
        tl = thread_ladder()
        call section("threads -- scaling at n = " // i2s(n) // " (dist=" // thread_dist // ")")
        call table_head()
        do fi = 1, list_len(families)
            fam = list_item(families, fi)
            do ti = 1, size(tl)
                call one_argsort(fam, thread_dist, n, tl(ti))
            end do
        end do
    end subroutine run_threads

    !> The operations that are not a plain argsort.
    !!
    !! Each is timed on real64 (the comparator path) and on the low-cardinality int64 family (the
    !! counting path), because those two take different routes through the engine and a change can
    !! easily improve one while regressing the other.
    subroutine run_ops()
        integer(int64) :: n
        !
        n = sizes(size(sizes))
        call section("ops -- the non-argsort operations at n = " // i2s(n))
        call table_head()
        call one_op("f64",   n)
        call one_op("i64lo", n)
    end subroutine run_ops

    ! ================================================================================
    ! One measured figure
    ! ================================================================================

    !> Times one (family, distribution, n, threads) argsort and prints one row.
    subroutine one_argsort(fam, dst, n, nthr)
        character(len=*), intent(in) :: fam      !! key family.
        character(len=*), intent(in) :: dst      !! input distribution.
        integer(int64), intent(in) :: n          !! rows.
        integer :: nthr                          !! threads to ask the engine for.
        real(real64) :: best
        integer(int64) :: nrep, r
        integer(int64) :: saved_checksum         !! checksum before the untimed warm-up call.
        !
        call build_data(fam, dst, n)
        nrep = reps(n)
        !
        ! ONE UNTIMED CALL FIRST, and it is not a formality. The permutation is an `intent(out)`
        ! allocatable, so every call allocates its own; the first at a given size pays to map those
        ! pages and later calls get the same block back already mapped. At reps >= 3 that amortises
        ! away, but `reps()` drops to 1 at the largest sizes, where the whole cost landed on
        ! whichever arm ran first -- **measured at 7.19 ns/elem against 3.05 for identical work** on
        ! the n = 5e7 i64lo arm. It read as a 2.3x threading win on an engine that ignored `threads=`
        ! entirely, which is what exposed it.
        !
        ! **That self-diagnosis is no longer available**: since Stage 4 step 1 the Fortran engine does
        ! honour `threads=`, so a threading-shaped curve is no longer prima facie impossible and this
        ! artifact would now look plausible instead of absurd. Trust
        ! `parquet_debug_sort_threads_used` for whether a team was opened, never the timings.
        !
        ! It bites hardest exactly where it is least visible: a FAST arm at a LARGE n, i.e. the
        ! counting fast path, which is the one arm feature_sort.md's Stage 6 bar requires not to
        ! regress at all. A slow arm at the same size (f64 at ~414 ns/elem) hides it inside 2% noise.
        !
        ! The checksum is saved and restored across the warm-up so that adding this changed no run's
        ! printed checksum -- earlier reports are compared against those values.
        saved_checksum = checksum
        best = huge(1.0_real64)
        call time_argsort(fam, n, nthr, best)
        checksum = saved_checksum
        !
        best = huge(1.0_real64)
        do r = 1_int64, nrep
            call time_argsort(fam, n, nthr, best)
        end do
        call verify_perm(fam, dst, n)
        call row(fam, dst, "argsort", n, nthr, nrep, best)
        call free_data()
    end subroutine one_argsort

    !> Times every non-argsort operation for one family and prints a row each.
    subroutine one_op(fam, n)
        character(len=*), intent(in) :: fam !! key family.
        integer(int64), intent(in) :: n     !! rows.
        real(real64) :: t0, t1, best
        integer(int64) :: nrep, r, nth, lb
        integer(int32), allocatable :: p32(:), rk32(:)
        real(real64), allocatable :: dv(:), mg(:)
        integer(int64), allocatable :: dvi(:), mgi(:)
        real(real64) :: pval
        integer(int64) :: pvali
        logical :: srt
        !
        call build_data(fam, "rand", n)
        nrep = reps(n)
        nth = n / 2_int64
        !
        ! partial_argsort: the leading 1% -- the shape a top-N query actually asks for.
        best = huge(1.0_real64)
        do r = 1_int64, nrep
            t0 = wtime()
            if (fam == "f64") then
                call pf_partial_argsort(vf64, p32, int(max(1_int64, n / 100_int64)))
            else
                call pf_partial_argsort(vi64, p32, int(max(1_int64, n / 100_int64)))
            end if
            t1 = wtime()
            best = min(best, t1 - t0)
            checksum = checksum + int(p32(1), int64)
        end do
        call row(fam, "rand", "partial1%", n, 1, nrep, best)
        !
        ! nth_element: the median.
        best = huge(1.0_real64)
        do r = 1_int64, nrep
            t0 = wtime()
            if (fam == "f64") then
                call pf_nth_element(vf64, nth, pval)
            else
                call pf_nth_element(vi64, nth, pvali)
            end if
            t1 = wtime()
            best = min(best, t1 - t0)
        end do
        if (fam == "f64") then
            checksum = checksum + int(pval, int64)
        else
            checksum = checksum + pvali
        end if
        call row(fam, "rand", "nth", n, 1, nrep, best)
        !
        ! unique and rank: both route through the engine's run-detection call.
        best = huge(1.0_real64)
        do r = 1_int64, nrep
            t0 = wtime()
            if (fam == "f64") then
                call pf_unique(vf64, dv)
            else
                call pf_unique(vi64, dvi)
            end if
            t1 = wtime()
            best = min(best, t1 - t0)
        end do
        if (fam == "f64") then
            checksum = checksum + int(size(dv, kind=int64), int64)
        else
            checksum = checksum + int(size(dvi, kind=int64), int64)
        end if
        call row(fam, "rand", "unique", n, 1, nrep, best)
        !
        best = huge(1.0_real64)
        do r = 1_int64, nrep
            t0 = wtime()
            if (fam == "f64") then
                call pf_rank(vf64, rk32)
            else
                call pf_rank(vi64, rk32)
            end if
            t1 = wtime()
            best = min(best, t1 - t0)
            checksum = checksum + int(rk32(1), int64)
        end do
        call row(fam, "rand", "rank", n, 1, nrep, best)
        !
        ! is_sorted: O(n), and the one operation whose cost should NOT move with the engine.
        ! Carried as this campaign's control arm -- see feature_benchmark_sort.md §3c.
        best = huge(1.0_real64)
        do r = 1_int64, nrep
            t0 = wtime()
            if (fam == "f64") then
                call pf_is_sorted(vf64, srt)
            else
                call pf_is_sorted(vi64, srt)
            end if
            t1 = wtime()
            best = min(best, t1 - t0)
            if (srt) checksum = checksum + 1_int64
        end do
        call row(fam, "rand", "is_sorted", n, 1, nrep, best)
        !
        ! lower_bound: O(log n), so this row is dominated by call overhead by design. It is here
        ! because the search path shares the tie-free comparator with everything else, and a
        ! comparator regression would show up here without any sorting in the way.
        best = huge(1.0_real64)
        do r = 1_int64, nrep
            call sort_in_place(fam, n)
            t0 = wtime()
            if (fam == "f64") then
                call pf_lower_bound(sf64, sf64(n / 3_int64), lb, assume_sorted=.true.)
            else
                call pf_lower_bound(si64, si64(n / 3_int64), lb, assume_sorted=.true.)
            end if
            t1 = wtime()
            best = min(best, t1 - t0)
            checksum = checksum + lb
        end do
        call row(fam, "rand", "lower_bound", n, 1, nrep, best)
        !
        ! merge: two already-ordered halves.
        best = huge(1.0_real64)
        call sort_in_place(fam, n)
        do r = 1_int64, nrep
            t0 = wtime()
            if (fam == "f64") then
                call pf_merge(sf64(1:n / 2_int64), sf64(n / 2_int64 + 1_int64:n), mg, assume_sorted=.true.)
            else
                call pf_merge(si64(1:n / 2_int64), si64(n / 2_int64 + 1_int64:n), mgi, assume_sorted=.true.)
            end if
            t1 = wtime()
            best = min(best, t1 - t0)
        end do
        if (fam == "f64") then
            checksum = checksum + int(size(mg, kind=int64), int64)
        else
            checksum = checksum + int(size(mgi, kind=int64), int64)
        end if
        call row(fam, "rand", "merge", n, 1, nrep, best)
        !
        call free_data()
    end subroutine one_op

    ! ================================================================================
    ! The timed calls, one per family
    ! ================================================================================

    !> One timed `pf_argsort` for the current data set. Splitting this out keeps the timer
    !! immediately around the library call, with the family dispatch outside it.
    !!
    !! **`--inner` exists because `system_clock` has a floor and a small sort is under it.** At
    !! n = 32 a whole argsort is a few hundred nanoseconds, so a single timed call reports one clock
    !! tick whatever it actually cost -- 31.24 ns/element at n = 32 and 15.63 at n = 64 is the same
    !! 1 us tick divided by two different n, not a measurement. Repeating the call inside the timer
    !! and dividing is what makes the small end of a size ladder mean anything. Rounds cannot
    !! substitute: the best of seven quantised readings is still quantised.
    !!
    !! It is NOT free of its own bias -- later iterations run on warm caches, and `perm` is
    !! reallocated per call on every one of them. Both apply equally to whatever two configurations
    !! are being compared, so a RATIO survives; an absolute ns/element at small n does not, and
    !! should not be quoted against a figure taken at `--inner=1`.
    subroutine time_argsort(fam, n, nthr, best)
        character(len=*), intent(in) :: fam   !! key family.
        integer(int64), intent(in) :: n       !! rows.
        integer, intent(in) :: nthr           !! threads to ask for.
        real(real64), intent(inout) :: best   !! running minimum, updated in place.
        real(real64) :: t0, t1
        integer :: it
        !
        t0 = wtime()
        do it = 1, inner
        select case (fam)
        case ("i32")
            if (permkind == 64) then
                call pf_argsort(vi32, perm64, threads=nthr, is_valid=vvalid)
            else
                call pf_argsort(vi32, perm32, threads=nthr, is_valid=vvalid)
            end if
        case ("i64", "i64lo")
            if (permkind == 64) then
                call pf_argsort(vi64, perm64, threads=nthr, is_valid=vvalid)
            else
                call pf_argsort(vi64, perm32, threads=nthr, is_valid=vvalid)
            end if
        case ("f32")
            if (permkind == 64) then
                call pf_argsort(vf32, perm64, threads=nthr, is_valid=vvalid)
            else
                call pf_argsort(vf32, perm32, threads=nthr, is_valid=vvalid)
            end if
        case ("f64")
            if (permkind == 64) then
                call pf_argsort(vf64, perm64, threads=nthr, is_valid=vvalid)
            else
                call pf_argsort(vf64, perm32, threads=nthr, is_valid=vvalid)
            end if
        case ("str")
            if (permkind == 64) then
                call pf_argsort(vstr, perm64, threads=nthr, is_valid=vvalid)
            else
                call pf_argsort(vstr, perm32, threads=nthr, is_valid=vvalid)
            end if
        case ("multi2", "multi3")
            ! Keys are built in build_data, OUTSIDE the timer -- see the program header.
            if (permkind == 64) then
                call pf_argsort(mkeys, perm64, threads=nthr)
            else
                call pf_argsort(mkeys, perm32, threads=nthr)
            end if
        case default
            write(error_unit,'(a)') "benchmark_sort_engine: unknown family '"//fam//"'"
            error stop 2
        end select
        end do
        t1 = wtime()
        best = min(best, (t1 - t0) / real(inner, real64))
        if (permkind == 64) then
            checksum = checksum + perm64(1) + perm64(n)
        else
            checksum = checksum + int(perm32(1), int64) + int(perm32(n), int64)
        end if
    end subroutine time_argsort

    !> Fills `sf64`/`si64` with a sorted copy, for the search and merge arms. Untimed.
    subroutine sort_in_place(fam, n)
        character(len=*), intent(in) :: fam !! key family.
        integer(int64), intent(in) :: n     !! rows.
        !
        integer(int64) :: keep
        !
        keep = n
        if (fam == "f64") then
            call pf_sort(vf64, sf64)       ! `sorted` is intent(out) allocatable -- it allocates
        else
            call pf_sort(vi64, si64)
        end if
        if (keep < 0_int64) return         ! `n` is documentation here; the arrays size themselves
    end subroutine sort_in_place

    ! ================================================================================
    ! Data generation
    ! ================================================================================

    !> Builds one (family, distribution, n) data set, and warms every buffer the timed call will
    !! touch. **The warm-up is not optional**: a freshly allocated array pays first-touch page
    !! faults on its first pass and never again, and that has been strong enough in this repository
    !! to reverse a comparison purely by which arm ran first.
    subroutine build_data(fam, dst, n)
        character(len=*), intent(in) :: fam !! key family.
        character(len=*), intent(in) :: dst !! input distribution.
        integer(int64), intent(in) :: n     !! rows.
        integer(int64) :: i, st, span
        real(real64) :: u
        !
        call free_data()
        st = seed_arg
        has_valid = (dst == "null001" .or. dst == "null10")
        !
        select case (fam)
        case ("i32")
            allocate(vi32(n))
            do i = 1_int64, n
                vi32(i) = int(shape_i(dst, i, n, st, .false.), int32)
            end do
        case ("i64")
            allocate(vi64(n))
            do i = 1_int64, n
                vi64(i) = shape_i(dst, i, n, st, .false.)
            end do
        case ("i64lo")
            ! Low cardinality -- 10 distinct values over the whole array, which is what puts the
            ! engine on its counting fast path and what exercises TIE ORDER a million times per
            ! run. A random real64 column of the same length contains essentially no ties at all,
            ! which is why a tie-order defect is invisible to the f64 arms.
            allocate(vi64(n))
            do i = 1_int64, n
                vi64(i) = shape_i(dst, i, n, st, .true.)
            end do
        case ("f32")
            allocate(vf32(n))
            do i = 1_int64, n
                vf32(i) = real(shape_r(dst, i, n, st), real32)
            end do
        case ("f64")
            allocate(vf64(n))
            do i = 1_int64, n
                vf64(i) = shape_r(dst, i, n, st)
            end do
        case ("str")
            allocate(character(len=strwidth) :: vstr(n))
            do i = 1_int64, n
                vstr(i) = str_of(shape_i(dst, i, n, st, .false.))
            end do
        case ("multi2", "multi3")
            ! A realistic multi-key shape: a low-cardinality primary that produces long tie runs,
            ! broken by a high-cardinality secondary. A multi-key benchmark whose primary key has
            ! no ties never reaches the second key at all and measures a single-key sort.
            allocate(vi64(n), vf64(n))
            do i = 1_int64, n
                vi64(i) = shape_i(dst, i, n, st, .true.)
                vf64(i) = shape_r(dst, i, n, st)
            end do
            if (fam == "multi3") then
                allocate(character(len=strwidth) :: vstr(n))
                do i = 1_int64, n
                    vstr(i) = str_of(shape_i("rand", i, n, st, .false.))
                end do
            end if
        case default
            write(error_unit,'(a)') "benchmark_sort_engine: unknown family '"//fam//"'"
            error stop 2
        end select
        !
        if (dst == "nan") call sprinkle_nan(fam, n, st)
        !
        if (has_valid) then
            allocate(vvalid(n))
            vvalid = .true.
            span = merge(1000_int64, 10_int64, dst == "null001")
            do i = span, n, span
                vvalid(i) = .false.
            end do
        end if
        !
        if (fam == "multi2" .or. fam == "multi3") then
            call mkeys%clear()
            call mkeys%add(vi64)
            call mkeys%add(vf64, descending=.true.)
            if (fam == "multi3") call mkeys%add(vstr)
        end if
        !
        ! Warm the destination. `perm` is intent(out) allocatable, so the library reallocates it on
        ! every call -- allocating it here does not remove that cost (which is real and is part of
        ! what the campaign measures), it removes the first-touch asymmetry between the first
        ! measured round and the rest.
        if (permkind == 64) then
            allocate(perm64(n))
            do i = 1_int64, n
                perm64(i) = i
            end do
            u = real(perm64(n), real64)
        else
            allocate(perm32(n))
            do i = 1_int64, n
                perm32(i) = int(i, int32)
            end do
            u = real(perm32(n), real64)
        end if
        checksum = checksum + int(u, int64) - int(u, int64)   ! keeps `u` live, contributes nothing
    end subroutine build_data

    !> Integer value for one position under a named distribution. `lowcard` folds the result onto
    !! ten distinct values, which is what puts an integer key on the counting fast path.
    function shape_i(dst, i, n, st, lowcard) result(v)
        character(len=*), intent(in) :: dst  !! distribution name.
        integer(int64), intent(in) :: i      !! 1-based position.
        integer(int64), intent(in) :: n      !! total rows.
        integer(int64), intent(inout) :: st  !! PRNG state.
        logical, intent(in) :: lowcard       !! .true. folds onto 10 distinct values.
        integer(int64) :: v
        !
        select case (dst)
        case ("sorted")
            v = i
        case ("reverse")
            v = n - i + 1_int64
        case ("equal")
            v = 42_int64
        case ("organ")
            ! Organ pipe: rises to the middle, then falls. Defeats median-of-three pivoting in a
            ! way none of the other shapes does.
            v = merge(i, n - i + 1_int64, i <= n / 2_int64)
        case default
            v = next_u63(st)
        end select
        !
        ! **The fold must PRESERVE the shape, which a modulus does not.** Folding a monotone
        ! sequence with `mod` turns "sorted" into a repeating 0..9 sawtooth -- so the sorted,
        ! reverse and organ arms of the low-cardinality family would all have been the same
        ! pseudo-random pattern under a different name, and the one family whose ordering the
        ! counting path decides would never have been handed an ordered input at all. Scaling the
        ! position into ten buckets keeps monotone inputs monotone; only the random shape, which
        ! has no order to preserve, is folded with a modulus.
        if (lowcard) then
            if (dst == "rand") then
                v = iand(v, huge(1_int64)) - iand(v, huge(1_int64)) / 10_int64 * 10_int64
            else if (dst /= "equal") then
                v = min(9_int64, max(0_int64, (v - 1_int64) * 10_int64 / max(n, 1_int64)))
            end if
        end if
    end function shape_i

    !> Real value for one position under a named distribution.
    function shape_r(dst, i, n, st) result(v)
        character(len=*), intent(in) :: dst  !! distribution name.
        integer(int64), intent(in) :: i      !! 1-based position.
        integer(int64), intent(in) :: n      !! total rows.
        integer(int64), intent(inout) :: st  !! PRNG state.
        real(real64) :: v
        !
        select case (dst)
        case ("sorted")
            v = real(i, real64)
        case ("reverse")
            v = real(n - i + 1_int64, real64)
        case ("equal")
            v = 42.0_real64
        case ("organ")
            v = real(merge(i, n - i + 1_int64, i <= n / 2_int64), real64)
        case default
            v = real(next_u63(st), real64) / real(huge(1_int64), real64)
        end select
    end function shape_r

    !> Replaces every thousandth element with a NaN. NaNs are ordinary VALUES to this library and
    !! are tiered by the engine, never by the caller -- so an arm that contains them is testing the
    !! tier logic, which is invisible to every other arm here.
    subroutine sprinkle_nan(fam, n, st)
        character(len=*), intent(in) :: fam !! key family.
        integer(int64), intent(in) :: n     !! rows.
        integer(int64), intent(inout) :: st !! PRNG state (unused; kept for symmetry).
        integer(int64) :: i
        real(real64) :: zero
        !
        zero = 0.0_real64
        if (st == 0_int64) zero = 0.0_real64      ! silences an unused-argument warning
        do i = 1000_int64, n, 1000_int64
            if (allocated(vf64)) vf64(i) = ieee_nan_r64()
            if (allocated(vf32)) vf32(i) = real(ieee_nan_r64(), real32)
        end do
        if (fam == "i32" .or. fam == "i64" .or. fam == "i64lo" .or. fam == "str") continue
    end subroutine sprinkle_nan

    !> A quiet NaN, built without a literal division so no compiler flag can trap it at build time.
    function ieee_nan_r64() result(v)
        use ieee_arithmetic, only : ieee_value, ieee_quiet_nan
        real(real64) :: v !! a quiet NaN.
        !
        v = ieee_value(1.0_real64, ieee_quiet_nan)
    end function ieee_nan_r64

    !> A fixed-width string whose ORDER follows the integer it is built from, and whose leading
    !! characters vary. Leading variation matters: a set of strings sharing a long prefix makes
    !! every comparison walk that prefix first, which measures a different thing entirely.
    function str_of(v) result(s)
        integer(int64), intent(in) :: v      !! the value to encode.
        character(len=strwidth) :: s         !! its fixed-width rendering.
        integer(int64) :: q
        integer :: k
        !
        s = repeat("a", strwidth)
        q = iand(v, 4611686018427387903_int64)
        do k = 1, strwidth
            s(k:k) = achar(iachar("a") + int(q - q / 26_int64 * 26_int64, kind(k)))
            q = q / 26_int64
        end do
    end function str_of

    !> Frees every data buffer. Called before each build and after each figure, so peak memory is
    !! one data set rather than all of them.
    subroutine free_data()
        if (allocated(vi32)) deallocate(vi32)
        if (allocated(vi64)) deallocate(vi64)
        if (allocated(vf32)) deallocate(vf32)
        if (allocated(vf64)) deallocate(vf64)
        if (allocated(vstr)) deallocate(vstr)
        if (allocated(vvalid)) deallocate(vvalid)
        if (allocated(perm32)) deallocate(perm32)
        if (allocated(perm64)) deallocate(perm64)
        if (allocated(sf64)) deallocate(sf64)
        if (allocated(si64)) deallocate(si64)
        call mkeys%clear()
        has_valid = .false.
    end subroutine free_data

    ! ================================================================================
    ! Verification -- a fast wrong answer must never be reported as a win
    ! ================================================================================

    !> Checks the last permutation before its timing is accepted. Two tiers, because only one of
    !! them is available for every arm:
    !!
    !!   * **Always**: it must be a permutation of 1..n. A sort that drops or duplicates an index
    !!     is the failure mode a co-rank off-by-one produces, and it is silent.
    !!   * **When the arm has no nulls and no NaNs**: it must actually order the values. Under
    !!     nulls or NaNs the ordering is tiered and asserting it here would duplicate the engine's
    !!     own tier logic in the harness, which is how a harness comes to agree with a bug.
    subroutine verify_perm(fam, dst, n)
        character(len=*), intent(in) :: fam !! key family.
        character(len=*), intent(in) :: dst !! input distribution.
        integer(int64), intent(in) :: n     !! rows.
        logical, allocatable :: seen(:)
        integer(int64) :: i, p, q
        !
        allocate(seen(n))
        seen = .false.
        do i = 1_int64, n
            p = perm_at(i)
            if (p < 1_int64 .or. p > n) then
                write(error_unit,'(a,i0,a,i0)') "VERIFY FAILED: perm entry ", i, " out of range: ", p
                error stop 1
            end if
            if (seen(p)) then
                write(error_unit,'(a,i0)') "VERIFY FAILED: duplicated index ", p
                error stop 1
            end if
            seen(p) = .true.
        end do
        deallocate(seen)
        !
        if (has_valid .or. dst == "nan") return
        if (fam == "multi2" .or. fam == "multi3") return   ! ordering is over several keys
        do i = 2_int64, n
            p = perm_at(i - 1_int64)
            q = perm_at(i)
            if (out_of_order(fam, p, q)) then
                write(error_unit,'(a,a,a,a,a,i0)') "VERIFY FAILED: ", fam, "/", dst, &
                    " not ordered at output position ", i
                error stop 1
            end if
        end do
    end subroutine verify_perm

    !> One entry of whichever permutation kind this run asked for.
    function perm_at(i) result(p)
        integer(int64), intent(in) :: i !! 1-based output position.
        integer(int64) :: p             !! the 1-based input index there.
        !
        if (permkind == 64) then
            p = perm64(i)
        else
            p = int(perm32(i), int64)
        end if
    end function perm_at

    !> .true. when the value at `p` sorts strictly after the value at `q`.
    function out_of_order(fam, p, q) result(bad)
        character(len=*), intent(in) :: fam !! key family.
        integer(int64), intent(in) :: p     !! earlier output position's input index.
        integer(int64), intent(in) :: q     !! later output position's input index.
        logical :: bad                      !! .true. when the pair is inverted.
        !
        select case (fam)
        case ("i32");            bad = vi32(p) > vi32(q)
        case ("i64", "i64lo");   bad = vi64(p) > vi64(q)
        case ("f32");            bad = vf32(p) > vf32(q)
        case ("f64");            bad = vf64(p) > vf64(q)
        case ("str");            bad = vstr(p) > vstr(q)
        case default;            bad = .false.
        end select
    end function out_of_order

