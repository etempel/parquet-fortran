#!/usr/bin/env python3
"""Generate the golden vectors that freeze `parquet_random`'s bit contract.

`parquet_random` produces values that are permanent: every one of them is baked into the
library's public promise, and changing any of them after release is a major-version event made
visible only through `pf_random_algorithm`. The vectors below are what pin that promise, so they
are derived here -- from an arbitrary-precision Python model of the contract -- rather than read
back out of a Fortran run, which could only ever confirm that the implementation agrees with
itself.

Emitted (COMMITTED to the repository, like every other generator's output -- nothing is generated
at build time, so the fpm build stays dependency-free):

  test/test_random_vectors.f90    module `test_random_vectors`: the Random123 known-answer
                                  vectors, and golden tables for pf_random_at, pf_random32_at,
                                  pf_random_bits_at, pf_random_int_at, pf_random_key and
                                  pf_random_fill_draws.

Usage:  tools/generate_random_golden_vectors.py [--check] [--self-test]

  --check      regenerate into memory and compare with the committed file; exit 1 on any
               difference (so CI, or a reviewer, can prove the committed output is current).
  --self-test  re-derive every PUBLISHED anchor -- the three Random123 KATs, the mix64 checksum,
               the wide-width oracle value, and the stable rows of the reference tables -- and
               exit 1 if any of them fails. This is what makes the emitted table trustworthy:
               without it the generator would merely be self-consistent.

NEVER HAND-EDIT A VECTOR. A contract change is an edit to the oracle below plus a regeneration;
an edit to the emitted table is a lie that `--check` will catch and nothing else would.

--------------------------------------------------------------------------------------------
ONE CONTRACT POINT WHERE THE PUBLISHED TABLE AND THE PUBLISHED PROSE DISAGREED, AND WHY THE
PROSE WON. The published table's rows for `draw = 2` and `draw = 5` were
generated by an earlier, scratch oracle that gave each `real64` value a WHOLE block (block
`d-1`, words `c0,c1`). Both documents' prose says the opposite in so many words -- value `d`
takes words `2d-2` and `2d-1`, i.e. block `(d-1)/2`, pair `mod(d-1,2)`, TWO values per block --
and three independent statements corroborate the prose:

  * the published prose: "two `real64` values at `draw = 1, 2` share block 0";
  * the reference's §5: whole-block consumption in a draw-axis fill is worth 1.68x-1.71x
    "simply not discarding half of each enciphering", and is "not available to an index-axis
    loop, where each block's second value is reserved for draw 2 at that index" -- neither
    sentence means anything if a scalar draw already consumes a whole block;
  * the reference's §2.2 note that a future `pf_random_fill_int` costs ~1/0.6 of its `real64`
    sibling per value -- a ratio that would be exactly 1.0 under one-block-per-value. (That 0.6
    is itself now obsolete: it described `/v1`, where the integer generic really did take a whole
    block. Under `/v2` the two fills are on one grid and the ratio is far closer to 1. It is still
    evidence for what the reference assumed about `real64`, which is the only thing it is cited
    for here.)

Nine of Table 1's twelve rows use `draw = 1`, where the two mappings coincide, which is why only
two rows ever disagreed. The mapping lives in `real64_word_indices()` below; reversing this
decision is an edit to that one function plus a regeneration.

`pf_random_int_at` USED TO BE THE ODD ONE OUT, and `/v2` fixed it. Under `philox4x32-10/v1` it
was the generic that really did take a whole block per value (`index = d - 1`, first pair only),
which is a plausible reason the scratch oracle above generalised that shape to `real64` as well.
The consequence was an exact collision -- `int_at(seed, i, lo, hi, d)` returned the bits of
`bits_at(seed, i, 2d-1)` -- so an integer at draw 2 and a real at draw 3 were the same
randomness. `/v2` gives it stride 2 like its siblings. Draw 1 is bit-identical under both, which
is why every anchor in this file survived the change untouched; every emitted vector at draw >= 2
did not. Same rule as above: the mapping is `int_at()` below, and reversing it is an edit there
plus a regeneration -- never an edit to the table.
--------------------------------------------------------------------------------------------

Regenerates `test/test_random_vectors.f90` -- the golden
vectors that freeze `parquet_random`'s bit contract (see Random numbers
(doc/pages/utilities/random.md)). It is the odd one out among the generators: its output is test
data rather than library source, and it is derived from an arbitrary-precision Python model of the
contract rather than from any Fortran run, because a table read back out of the implementation
could only ever confirm that the implementation agrees with itself. `--self-test` re-derives every
published anchor -- the three Random123 known-answer vectors, the `mix64` checksum, the wide-width
oracle value and the stable rows of the reference tables -- and refuses to regenerate anything if
one of them fails; that is what makes the emitted table evidence rather than mere self-
consistency, so run it before trusting a regeneration. `--check` verifies the committed output as
usual. Never hand-edit a vector: a contract change is an edit to the oracle in the script plus a
regeneration, and every value it emits is permanent (changing one is a major-version event,
visible only through `pf_random_algorithm`). Maintainer-only (stripped from the fpm-published
package).
"""

