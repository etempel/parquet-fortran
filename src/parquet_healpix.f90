            real(real64), intent(out) :: phi !! longitude of the centre, radians, in [0, 2*pi).
        end subroutine hpx_pix2ang_ring_i32

        !> Centre direction of a RING pixel, int64 kinds. See the `pf_pix2ang_ring` generic.
        pure elemental module subroutine hpx_pix2ang_ring_i64(nside, ipix, theta, phi)
            integer(int64), intent(in) :: nside !! resolution parameter, a positive power of two.
            integer(int64), intent(in) :: ipix !! RING pixel index, 0-based.
            real(real64), intent(out) :: theta !! colatitude of the centre, radians, in [0, pi].
