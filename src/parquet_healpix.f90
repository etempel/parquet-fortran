    public :: pf_chord2_from_angle, pf_angle_from_chord2
    public :: pf_ang2pix_ring_bulk, pf_ang2pix_nest_bulk
    public :: pf_pix2ang_ring_bulk, pf_pix2ang_nest_bulk
    public :: pf_vec2pix_ring_bulk, pf_vec2pix_nest_bulk
