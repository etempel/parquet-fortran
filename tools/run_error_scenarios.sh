#!/usr/bin/env bash
# Runs every scenario supported by the test/error_scenarios.f90 helper program
# and checks that each one aborts (or exits cleanly) as expected. This is the
# same check test_errors.f90 does from inside the test-drive suite, exposed
# here as a standalone script for manual/CI use without going through fpm's
# test-drive runner.
#
# Keep this list in sync with the `select case` in test/error_scenarios.f90 --
# it is intentionally a complete, independent mirror of every scenario name
# there (not a curated subset), since a script that silently only covers some
# scenarios would be misleading for the "quick manual check"/"CI step" use
# this is documented for in README.md.
set -uo pipefail

cd "$(dirname "$0")/.."

# A per-scenario wall-clock cap, so one wedged scenario cannot stall the whole run.
#
# This is not hypothetical: a scenario that provokes the concurrency guard from many OpenMP
# threads was observed hanging forever inside glibc's abort() (192 threads parked on one lock),
# which stalled a full `fpm test --profile debug` under ifx indefinitely. The library-side fix is
# in src/parquet_wrapper.cpp's fatal path; this cap is the belt to that braces, and it is what
# turns any future hang -- from any cause -- into a reported failure instead of a hung pipeline.
#
# SIGKILL rather than the default SIGTERM on purpose: the Fortran runtimes install a SIGTERM
# handler that prints a traceback, and a process wedged inside a lock cannot run it either, so a
# TERM would be ignored by exactly the processes this needs to kill. `timeout` still reports 124
# when it fires, which is the sentinel the callers below and test_errors.f90 key on.
#
# macOS ships no `timeout` (coreutils installs it as `gtimeout`), so an absent one degrades to
# running unguarded rather than failing the run.
#
# The probe RUNS the command with the flags actually used rather than asking whether the name
# exists, because existence does not imply this syntax: MacPorts ships a BSD-style
# /opt/local/bin/timeout whose usage is `timeout [-signal] time command`, so `command -v timeout`
# succeeds and `-s KILL` is then rejected. Every scenario would capture
# "usage: timeout [-signal] time command..." as its own output. Running the probe falls through
# to `gtimeout` instead, and covers the absent case for free -- a missing command exits nonzero
# too. Keep the probe and the real invocation using the same flags.
SCENARIO_TIMEOUT="${PARQUET_SCENARIO_TIMEOUT:-120}"
if timeout -s KILL 1 true >/dev/null 2>&1; then
    TIMEOUT_CMD="timeout -s KILL $SCENARIO_TIMEOUT"
elif gtimeout -s KILL 1 true >/dev/null 2>&1; then
    TIMEOUT_CMD="gtimeout -s KILL $SCENARIO_TIMEOUT"
else
    TIMEOUT_CMD=""
fi

# Worker mode: this script re-invokes itself (via xargs -P below) as
#   run_error_scenarios.sh __worker__ <bin> <results_dir> <idx> <scenario> <expect_abort>
# to run exactly one scenario and record its PASS/FAIL line + status to
# "$results_dir/$idx.{status,line}". This lets the scenario list further down
# be dispatched across several worker processes in parallel via xargs -P
# instead of one `fpm test error_scenarios -- ...` invocation at a time --
# each scenario is an independent process writing to its own uniquely-named
# file under test_run/, so there is no cross-scenario interference. Kept as a
# re-invocation of this same file (rather than a separate helper script or an
# exported shell function) so it works unchanged under the old bash (3.2, no
# `export -f`/`wait -n`) macOS ships as /bin/bash.
if [ "${1:-}" = "__worker__" ]; then
    bin="$2"
    results_dir="$3"
    idx="$4"
    scenario="$5"
    expect_abort="$6"

    $TIMEOUT_CMD "$bin" "$scenario" > /dev/null 2>&1
    exitstat=$?

    # The cap above fired: the scenario neither finished nor aborted. That is a hang, and it must
    # be reported as one -- a bare "nonzero exit" test would otherwise read it as a successful
    # abort and PASS, which is the failure this cap exists to expose rather than hide.
    #
    # BOTH codes are the timeout, and checking only the documented one is wrong: `timeout` exits
    # 124 when it fires, EXCEPT that with `-s KILL` the child dies by a signal it cannot catch and
    # the status is 128+9 = 137 instead. Verified here rather than assumed -- keying on 124 alone
    # let a forced timeout report [PASS] with exit=137.
    if [ "$exitstat" -eq 124 ] || [ "$exitstat" -eq 137 ]; then
        echo "FAIL" > "$results_dir/$idx.status"
        printf "[FAIL] %-50s TIMED OUT after %ss (killed; neither finished nor aborted)\n" \
            "$scenario" "$SCENARIO_TIMEOUT" > "$results_dir/$idx.line"
        exit 0
    fi

    # exit code 97 means error_scenarios.f90's `case default` was hit --
    # i.e. this scenario name isn't recognized there (typo, or renamed on
    # one side but not the other) -- distinct from a genuine abort so this
    # doesn't silently "pass" by coincidence.
    if [ "$exitstat" -eq 97 ]; then
        status=FAIL
        line=$(printf "[FAIL] %-50s scenario name not recognized by error_scenarios.f90 (typo?)" "$scenario")
    else
        if [ "$exitstat" -ne 0 ]; then aborted=1; else aborted=0; fi
        if [ "$aborted" -eq "$expect_abort" ]; then
            status=PASS
            line=$(printf "[PASS] %-50s (exit=%d, expected abort=%s)" "$scenario" "$exitstat" "$expect_abort")
        else
            status=FAIL
            line=$(printf "[FAIL] %-50s (exit=%d, expected abort=%s)" "$scenario" "$exitstat" "$expect_abort")
        fi
    fi
    echo "$status" > "$results_dir/$idx.status"
    echo "$line" > "$results_dir/$idx.line"
    exit 0
fi

