!> The HEALPix sphere pixelisation: position <-> pixel, scheme conversion, and disc queries.
!!
!! HEALPix divides the sphere into `12*nside**2` pixels of exactly equal area, arranged on rings of
!! constant latitude. `parquet_healpix` implements the part of it a program actually needs to hold
!! sky data on a grid: converting a direction to the pixel containing it and back, converting
!! between the two pixel-numbering schemes, and enumerating the pixels of a disc.
!!
!! **Written from the published algorithm, not translated from any implementation.** The
!! pixelisation is described completely in Gorski et al. 2005, ApJ 622, 759, and the geometry is
!! elementary; every formula here was derived from that paper and then checked against reference
!! vectors (`test/test_healpix_vectors.f90`, generated by `tools/generate_healpix_reference.py`).
!! No HEALPix source was consulted while writing this module, and none should be if it is ever
!! re-derived -- the paper plus the vectors are sufficient, and they are what keeps this library
!! BSD-3-Clause while `libhealpix` is GPL-2.0.
!!
!! **This module is Arrow-free by construction and that is the point of its tier.** It reaches
!! `iso_fortran_env`, `ieee_arithmetic` and `parquet_settings_base`, and nothing else, so
!! `use parquet_healpix` in a downstream project compiles six Fortran files rather than the
!! sixty-odd the reader/writer stack costs. `check_parquet_healpix_stays_arrow_free`
!! (tools/check_source_conventions.py) and `tools/module_footprints.txt` are what keep that true --
!! a `use` line added here can silently multiply what every consumer compiles, and no test can see
!! it happen.
!!
!! **No module state, no saved variables, no lazy initialisation.** Every procedure here is a
!! function of its arguments alone, so the whole module is thread-safe with nothing to arrange and
!! the scalar conversions are `pure elemental`. Do not add a cache: a `logical, save :: ready`
!! reached from inside a parallel region is a check-then-act on shared state.
!!
!! **Two conventions a caller must get right, and neither has a default this module can pick:**
!!
!! * `theta` is COLATITUDE from the north pole in radians, so `theta = pi/2 - dec`. A mirrored
!!   frame (`theta = pi/2 + dec`) is in live use in several projects that feed this module, and is
!!   self-consistent -- a reflection preserves angular distance -- but mixing the two searches the
!!   wrong hemisphere silently. This module takes HEALPix-native `theta`/`phi` and unit vectors
!!   only, and offers no RA/Dec layer, precisely so that the choice stays visible at each call.
!! * A pixel INDEX runs `0 .. 12*nside**2 - 1`, as the pixelisation itself defines it. The
!!   `listpix` array `pf_query_disc` fills is 1-based, like every other user-facing array in this
!!   library. The array base and the pixel base are different things and are the pair most easily
!!   conflated: `listpix(1)` holds the first pixel found, and its VALUE may well be 0.
module parquet_healpix
