        !> overlapping pixel is returned, and no pixel whose centre lies farther than
        !> `radius + max_pixrad(nside)` is returned. That bound is what a caller can rely on -- a
        !> returned pixel is not necessarily an overlapping one, and filtering the result is the
        !> caller's business.
