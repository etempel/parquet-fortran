def int_rows():
    rows = []
    for seed, stream, lo, hi, draw, note in INT_CASES:
        value, retries = int_at(seed, stream, lo, hi, draw)
        rows.append((seed, stream, lo, hi, draw, value, retries, note))
    return rows


#: Rows whose whole point is that a retry fires; the suite asserts the count is non-zero, so a
#: retry path that is compiled and never entered cannot pass as tested.
def retrying_int_rows():
    """Streams at a width close to 2**64 * 2/3, where rejection is most likely."""
    lo, hi = INT64_MIN, INT64_MIN + int(0.672 * 2 ** 64) - 1
    rows = []
    for stream in range(1, 400):
        value, retries = int_at(12345, stream, lo, hi)
        if retries:
            rows.append((12345, stream, lo, hi, 1, value, retries, "retry chain %d" % retries))
        if len(rows) == 8:
            break
    return rows


