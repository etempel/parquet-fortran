    ! ---- Interfaces: ring geometry and the Morton codec ----
    !
    ! Private to the module and its submodules. Implemented in parquet_healpix_core; declared here
    ! rather than contained in the module because gfortran gives a private module-contained
    ! procedure internal linkage, so a submodule calling one fails to LINK while compiling cleanly.

    interface
        !> Centre `z` of ring `i`, counted from the north pole.
        !>
        !> The single place the three regions' `z` formulas live. Every consumer of a ring's
        !> latitude -- the pixel centre, the disc walk's band test, the per-ring threshold -- goes
        !> through this one function, so the module cannot disagree with itself about where a ring
        !> is.
        pure module function hpx_ring_z(nside, i) result(z)
            integer(int64), intent(in) :: nside !! resolution parameter.
            integer(int64), intent(in) :: i !! ring index, 1 .. 4*nside-1, from the north pole.
            real(real64) :: z !! cosine of the ring's colatitude.
        end function hpx_ring_z

        !> Where ring `i` starts, how many pixels it holds, and whether it is offset in longitude.
        pure module subroutine hpx_ring_first(nside, i, first, nr, shifted)
            integer(int64), intent(in) :: nside !! resolution parameter.
            integer(int64), intent(in) :: i !! ring index, 1 .. 4*nside-1, from the north pole.
            integer(int64), intent(out) :: first !! RING index of the ring's first pixel.
            integer(int64), intent(out) :: nr !! number of pixels on the ring.
            integer(int64), intent(out) :: shifted !! 1 when centres are offset by half a pixel.
        end subroutine hpx_ring_first

        !> Largest ring index whose centre `z` is at or above `z`; 0 when none is.
        !>
        !> Used only to bracket the disc walk's band of rings, which is then widened by one ring on
        !> each side, so an answer off by one costs three membership tests and never a wrong result.
        pure module function hpx_ring_above(nside, z) result(i)
            integer(int64), intent(in) :: nside !! resolution parameter.
            real(real64), intent(in) :: z !! cosine of a colatitude, in [-1, 1].
            integer(int64) :: i !! the ring index, 0 when the whole sphere lies below `z`.
        end function hpx_ring_above

        !> Ring index of a north-cap RING pixel.
        !>
        !> Inverts `p = 2*i*(i-1) + j` for `i`. The square root seeds the answer and the two
        !> single-step corrections make it exact: at `nside = 2**29` the argument reaches 7e18,
        !> where a double's relative error of 1e-16 is still far below one ring.
        pure module function hpx_cap_ring(p) result(i)
            integer(int64), intent(in) :: p !! a RING index within the north polar cap.
            integer(int64) :: i !! the ring the pixel lies on, 1-based from the pole.
        end function hpx_cap_ring

        !> RING pixel -> the ring it lies on and its position within that ring.
        pure module subroutine hpx_ring_decompose(nside, p, i, j, nr, shifted)
            integer(int64), intent(in) :: nside !! resolution parameter.
            integer(int64), intent(in) :: p !! RING pixel index, 0-based.
            integer(int64), intent(out) :: i !! ring index, 1 .. 4*nside-1, from the north pole.
            integer(int64), intent(out) :: j !! index within the ring, 0-based.
            integer(int64), intent(out) :: nr !! number of pixels on that ring.
            integer(int64), intent(out) :: shifted !! 1 when centres are offset by half a pixel.
        end subroutine hpx_ring_decompose

        !> Centre of a RING pixel as `(z, phi)`, with no `acos`/`cos` round trip.
        pure module subroutine hpx_pix2zphi_ring(nside, p, z, phi)
            integer(int64), intent(in) :: nside !! resolution parameter.
            integer(int64), intent(in) :: p !! RING pixel index, 0-based.
            real(real64), intent(out) :: z !! cosine of the centre's colatitude.
            real(real64), intent(out) :: phi !! the centre's longitude, radians, in [0, 2*pi).
        end subroutine hpx_pix2zphi_ring

        !> `(ring, index-in-ring)` -> NEST pixel index.
        !>
        !> The half of `pf_ring2nest` that follows the ring decomposition, split out because the
        !> disc walk already knows both coordinates: going through `pf_ring2nest` there would
        !> re-derive them, paying a cap-ring inversion per emitted pixel.
        pure module function hpx_ringij2nest(nside, jr, j) result(ipnest)
            integer(int64), intent(in) :: nside !! resolution parameter.
            integer(int64), intent(in) :: jr !! ring index, 1 .. 4*nside-1, from the north pole.
            integer(int64), intent(in) :: j !! index within the ring, 0-based.
            integer(int64) :: ipnest !! the pixel's NEST index.
        end function hpx_ringij2nest

        !> Largest angular distance from a pixel centre to one of its own corners, in radians.
        !>
        !> This is the margin `pf_query_disc`'s inclusive mode enlarges its radius by, and the
        !> bound that mode publishes. It is attained on the first equatorial ring, whose pixels are
        !> the most elongated, at the corner lying on the quadrant meridian.
        pure module function hpx_max_pixrad(nside) result(r)
            integer(int64), intent(in) :: nside !! resolution parameter, a positive power of two.
            real(real64) :: r !! the largest centre-to-corner angle, radians.
        end function hpx_max_pixrad

        !> Largest centre-to-corner angle at `nside`, int32 kind. See the `pf_max_pixrad` generic.
        pure elemental module function hpx_max_pixrad_i32(nside) result(r)
            integer(int32), intent(in) :: nside !! resolution parameter, a positive power of two.
            real(real64) :: r !! the largest centre-to-corner angle, radians.
        end function hpx_max_pixrad_i32

        !> Largest centre-to-corner angle at `nside`, int64 kind. See the `pf_max_pixrad` generic.
        pure elemental module function hpx_max_pixrad_i64(nside) result(r)
            integer(int64), intent(in) :: nside !! resolution parameter, a positive power of two.
            real(real64) :: r !! the largest centre-to-corner angle, radians.
        end function hpx_max_pixrad_i64

        !> Angular separation of two directions, in radians.
        !>
        !> `atan2(|v1 x v2|, v1.v2)` rather than `acos` of the dot product: accurate to about an ulp
        !> across the whole range, where the `acos` form loses half its digits near 0 and pi. The
        !> inputs need not be unit vectors -- the formula is scale-invariant -- and two parallel
        !> zero vectors give 0 rather than an exception.
        pure module subroutine pf_angdist(vec1, vec2, dist)
            real(real64), intent(in) :: vec1(3) !! first direction; any nonzero length.
            real(real64), intent(in) :: vec2(3) !! second direction; any nonzero length.
            real(real64), intent(out) :: dist !! the angle between them, radians, in [0, pi].
        end subroutine pf_angdist
    end interface

    ! ---- Interfaces: disc queries ----
    !
    ! Implemented in submodule parquet_healpix_query.

    interface
        !> Pixels of a disc, int32 kinds. See `hpx_query_disc_i64` for the contract.
        module subroutine hpx_query_disc_i32(nside, vec, radius, listpix, nlist, scheme, inclusive)
            integer(int32), intent(in) :: nside !! resolution parameter, a positive power of two.
            real(real64), intent(in) :: vec(3) !! direction of the disc centre; any nonzero length.
            real(real64), intent(in) :: radius !! disc radius, radians, >= 0.
            integer(int32), intent(out) :: listpix(:) !! filled from element 1 with 0-based indices.
            integer(int32), intent(out) :: nlist !! how many elements of `listpix` were filled.
            integer, intent(in), optional :: scheme !! `PF_HP_RING` (default) or `PF_HP_NEST`.
            logical, intent(in), optional :: inclusive !! overlap superset; default `.false.`.
        end subroutine hpx_query_disc_i32

        !> Pixels of a disc: every pixel of the pixelisation lying within `radius` of `vec`.
        !>
        !> **`inclusive = .false.` (the default) has an exact specification**: the pixels whose
        !> CENTRES lie within `radius` of `vec`. Reproducible against any correct implementation
        !> and testable by brute force.
        !>
        !> **`inclusive = .true.` returns the pixels OVERLAPPING the disc**, which every
        !> implementation computes as a bounded superset. The contract this one publishes is: every
        !> overlapping pixel is returned, and no pixel whose centre lies farther than
        !> `radius + max_pixrad(nside)` is returned. That bound is what a caller can rely on -- a
        !> returned pixel is not necessarily an overlapping one, and filtering the result is the
        !> caller's business.
        !>
        !> **Output ordering is ascending pixel index for `PF_HP_RING`, and UNSPECIFIED for
        !> `PF_HP_NEST`.** The ring walk emits ascending RING indices naturally, so that half is
        !> free; the RING-to-NEST conversion destroys monotonicity, and sorting afterwards would
        !> cost more than any caller needs. The NEST order is deterministic for a given input, but
        !> it is not promised and may change -- compare NEST results as sets.
        !>
        !> **`listpix` is filled from element 1; the pixel VALUES it holds are 0-based.** Those are
        !> two different bases and are the pair most easily conflated. `nlist` is the count, so the
        !> result is `listpix(1:nlist)`, and a value of 0 in it means pixel zero rather than an
        !> empty slot.
        !>
        !> **A disc smaller than about 1e-08 radians cannot be resolved, and returns too many
        !> pixels rather than too few.** Membership is decided against `cos(radius)`, whose
        !> distance from 1 is about `radius**2/2` -- so the radius is resolved to a fraction
        !> `2.2e-16/radius**2` of itself, which is 2e-10 at a milliradian and 1 at 1.05e-08 rad
        !> (0.0022 arcsec), where `cos(radius)` is exactly 1.0 and the comparison stops
        !> distinguishing anything. This is a property of a double-precision disc query rather than
        !> of this implementation, and it only becomes reachable at extreme resolution: a
        !> pixel-scale disc is resolvable through `nside = 2**28` and degenerates at `2**29`. Every
        !> `nside` a survey actually uses is many orders away from it.
        !>
        !> **No IEEE exception is raised on any input that passes validation.** That is the point of
        !> this module existing: a caller running under `-ffpe-trap=zero,invalid` needs no guard
        !> around these calls.
        !>
        !> Aborts, with a message naming the routine and the offending value, when `nside` is not a
        !> positive power of two or exceeds this kind's ceiling, when `radius` is negative or NaN,
        !> when `vec` holds a NaN or has zero length, when `scheme` is neither selector, or when
        !> `listpix` is too small to hold the result.
        module subroutine hpx_query_disc_i64(nside, vec, radius, listpix, nlist, scheme, inclusive)
            integer(int64), intent(in) :: nside !! resolution parameter, a positive power of two.
            real(real64), intent(in) :: vec(3) !! direction of the disc centre; any nonzero length.
            real(real64), intent(in) :: radius !! disc radius, radians, >= 0; above pi acts as pi.
            integer(int64), intent(out) :: listpix(:) !! filled from element 1 with 0-based indices.
            integer(int64), intent(out) :: nlist !! how many elements of `listpix` were filled.
            integer, intent(in), optional :: scheme !! `PF_HP_RING` (default) or `PF_HP_NEST`.
            logical, intent(in), optional :: inclusive !! overlap superset; default `.false.`.
        end subroutine hpx_query_disc_i64

        !> The disc walk itself, over `integer(int64)` and writing into whichever output is present.
        !>
        !> Both output arrays are optional and exactly one is passed, which is what lets the two
        !> public kinds share one walk without the int32 form allocating a temporary the size of the
        !> caller's buffer -- the same shape `pf_spatial_index`'s scans use for the same reason.
        module subroutine hpx_query_disc_core(nside, vec, radius, scheme, inclusive, nlist, cap, &
                                              out32, out64)
            integer(int64), intent(in) :: nside !! resolution parameter, already validated.
            real(real64), intent(in) :: vec(3) !! disc centre, already validated, any length.
            real(real64), intent(in) :: radius !! disc radius, radians, already validated.
            integer, intent(in) :: scheme !! `PF_HP_RING` or `PF_HP_NEST`, already validated.
            logical, intent(in) :: inclusive !! whether to return the overlap superset.
            integer(int64), intent(out) :: nlist !! number of pixels written.
            integer(int64), intent(in) :: cap !! capacity of the output array, in elements.
            integer(int32), intent(out), optional :: out32(:) !! int32 output buffer.
            integer(int64), intent(out), optional :: out64(:) !! int64 output buffer.
        end subroutine hpx_query_disc_core

        !> Validates the arguments shared by both `pf_query_disc` kinds, and aborts on any fault.
        module subroutine hpx_check_disc_args(nside, nside_max, vec, radius, scheme)
            integer(int64), intent(in) :: nside !! the resolution parameter to check.
            integer(int64), intent(in) :: nside_max !! the ceiling for the caller's integer kind.
            real(real64), intent(in) :: vec(3) !! the disc centre to check.
            real(real64), intent(in) :: radius !! the disc radius to check.
            integer, intent(in) :: scheme !! the resolved scheme selector to check.
        end subroutine hpx_check_disc_args
    end interface

    ! ---- Interfaces: small shared helpers ----
    !
    ! Implemented in parquet_healpix_core. These are declared rather than contained for the same
    ! linkage reason as the geometry helpers above: a private module-contained procedure has
    ! internal linkage under gfortran, so a submodule calling one compiles and then fails to link.

    interface
        !> Spreads the low 32 bits of `v` into the even bit positions of a 64-bit result.
        !>
        !> The standard five-step Morton spread, and half of the NEST index's construction. Done
        !> with masks rather than a lookup table so that the module carries no data at all -- there
        !> is then nothing for a parallel region to share, and nothing to initialise lazily.
        pure module function hpx_spread_bits(v) result(s)
            integer(int64), intent(in) :: v !! the value whose low 32 bits are spread.
            integer(int64) :: s !! the spread result, occupying the even bits of 64.
        end function hpx_spread_bits

        !> Gathers the even bit positions of `v` back into a contiguous low field.
        !>
        !> The exact inverse of `hpx_spread_bits`.
        pure module function hpx_compact_bits(v) result(c)
            integer(int64), intent(in) :: v !! the interleaved value to compact.
            integer(int64) :: c !! the even bits of `v`, packed into the low half.
        end function hpx_compact_bits

        !> Whether `nside` is a positive power of two at or below `limit`.
        pure module function hpx_nside_ok(nside, limit) result(ok)
            integer(int64), intent(in) :: nside !! the value to test.
            integer(int64), intent(in) :: limit !! the largest acceptable value.
            logical :: ok !! `.true.` when `nside` is usable.
        end function hpx_nside_ok

        !> Renders an integer as its shortest decimal text, for an `error stop` message.
        !>
        !> A subroutine with an allocatable `intent(out)` argument rather than a function returning
        !> `character(len=:), allocatable`, per the project-wide rule: gfortran's codegen for
        !> receiving such a result races on a hidden length temporary when called concurrently.
        module subroutine hpx_itoa(value, text)
            integer(int64), intent(in) :: value !! the number to render.
            character(len=:), allocatable, intent(out) :: text !! its decimal text, unpadded.
        end subroutine hpx_itoa

        !> Renders a real as a short decimal text, for an `error stop` message.
        module subroutine hpx_rtoa(value, text)
            real(real64), intent(in) :: value !! the number to render.
            character(len=:), allocatable, intent(out) :: text !! its text, unpadded.
        end subroutine hpx_rtoa
    end interface

