# ---------------------------------------------------------------------------------------------
# The contract, as arbitrary-precision integers.  Every constant here is permanent bit contract.
# ---------------------------------------------------------------------------------------------

M32 = 0xFFFFFFFF
MASK64 = (1 << 64) - 1
INT64_MIN = -(1 << 63)
INT64_MAX = (1 << 63) - 1

PHILOX_M0 = 0xD2511F53
PHILOX_M1 = 0xCD9E8D57
PHILOX_W0 = 0x9E3779B9
PHILOX_W1 = 0xBB67AE85
PHILOX_ROUNDS = 10

MIX_A = 0xBF58476D1CE4E5B9
MIX_B = 0x94D049BB133111EB

#: Offset in label space that keeps a retried draw's key off `pf_random_key(seed, n)`, which is
#: a documented user idiom -- without it 100 % of retried draws share that family's block.
RETRY_TAG = 0x5A17000000000000

#: The widest range served by the 32-bit candidate grid.  **Frozen contract, never a setting.**
#: A block is four 32-bit words, so a narrow integer draw costs a quarter of an enciphering
#: instead of a half.  The price is a rejection rate of `(2**32 mod s)/2**32`, which rises with
#: `s` and peaks at 33.3 % just above `2**32/3`; capping the WIDTH at `2**24` bounds the worst
#: case over every admitted `s` at 0.389 %, attained at `s = 16711936`.  The cap is on the width
#: `hi - lo + 1`, never on how many values are drawn -- the two coincide for a resample and differ
#: for everything else.
NARROW32_CAP = 1 << 24


def u64(x):
    """The unsigned 64-bit pattern of `x`."""
    return x & MASK64


def signed64(x):
    """`x`'s 64-bit pattern read as a signed `integer(int64)`."""
    x = u64(x)
    return x - (1 << 64) if x > INT64_MAX else x


def philox4x32_10(c0, c1, c2, c3, k0, k1):
    """Philox4x32-10 on four 32-bit counter words and two 32-bit key words."""
    for r in range(PHILOX_ROUNDS):
        p0 = PHILOX_M0 * c0
        p1 = PHILOX_M1 * c2
        hi0, lo0 = p0 >> 32, p0 & M32
        hi1, lo1 = p1 >> 32, p1 & M32
        c0, c1, c2, c3 = (hi1 ^ c1 ^ k0) & M32, lo1, (hi0 ^ c3 ^ k1) & M32, lo0
        if r != PHILOX_ROUNDS - 1:       # the key bump is skipped after the final round
            k0 = (k0 + PHILOX_W0) & M32
            k1 = (k1 + PHILOX_W1) & M32
    return c0, c1, c2, c3


def key_of(k):
    """Split a 64-bit key into Philox's two 32-bit key words: low half first."""
    k = u64(k)
    return k & M32, (k >> 32) & M32


def block(seed, stream, index, key=None):
    """Block `index` (0-based) of `stream` under `seed`, or under an explicit retry `key`."""
    k0, k1 = key_of(seed if key is None else key)
    s = u64(stream)
    return philox4x32_10(index & M32, (index >> 32) & M32, s & M32, (s >> 32) & M32, k0, k1)


def word(seed, stream, index):
    """Word `index` (0-based) of the stream: blocks 0,1,2,... each giving c0,c1,c2,c3 in order."""
    return block(seed, stream, index // 4)[index % 4]


def clamp_draw(draw):
    """`draw < 1` is a documented precondition violation, absorbed so tier 0 stays total."""
    return draw if draw >= 1 else 1


def real64_word_indices(draw):
    """The two word indices a `real64`/raw-bits value occupies.  THE contract point above."""
    d = clamp_draw(draw)
    return 2 * (d - 1), 2 * (d - 1) + 1


def bits_at(seed, stream, draw=1):
    """`pf_random_bits_at`: the first word is the LOW half of the 64-bit pattern."""
    lo_index, hi_index = real64_word_indices(draw)
    return (word(seed, stream, hi_index) << 32) | word(seed, stream, lo_index)


def at(seed, stream, draw=1):
    """`pf_random_at`: the top 53 bits of the pattern, scaled to [0, 1).  Exact in real64."""
    return float(bits_at(seed, stream, draw) >> 11) * (2.0 ** -53)


def at32(seed, stream, draw=1):
    """`pf_random32_at`: the top 24 bits of ONE word.  Its own sequence, not a narrowing."""
    return float(word(seed, stream, clamp_draw(draw) - 1) >> 8) * (2.0 ** -24)


def mix64(z):
    """The SplitMix64 finaliser.  `mix64(0) == 0`, and it is a bijection."""
    z = u64(z)
    z = u64((z ^ (z >> 30)) * MIX_A)
    z = u64((z ^ (z >> 27)) * MIX_B)
    return z ^ (z >> 31)


def random_key(seed, label):
    """`pf_random_key`: a derived key IS a seed, so it composes by nesting."""
    return mix64(mix64(seed) ^ u64(label))


def retry_key(seed, attempt):
    """The key for retry `attempt` (1-based).  Re-keys; never tweaks, and never moves the counter."""
    return mix64(mix64(seed) ^ u64(attempt ^ RETRY_TAG))


def umod_2p64(s):
    """`2**64 mod s` for `s` read as unsigned.  Correct at and above 2**63, where the naive
    spelling silently makes up to half the requested range unreachable."""
    return (1 << 64) % s


def int_at(seed, stream, lo, hi, draw=1):
    """`pf_random_int_at`: exact rejection, on ONE OF TWO GRIDS chosen by the range's WIDTH.

    **Narrow (`1 <= s <= NARROW32_CAP`): stride 1, a single 32-bit candidate.**  Draw `d` is word
    `d - 1` -- exactly the grid `pf_random32_at` walks -- so one enciphering serves four draws
    instead of two.  `x < 2**32` and `s <= 2**24` make `x * s` fit an ordinary signed 64-bit
    integer, so the reduction needs no 128-bit product.  The rejection test is the exact 32-bit
    analogue, accept iff `low32(x*s) >= 2**32 mod s`, so the result is exactly uniform rather than
    uniform to within `2**-32`.

    **Wide (everything else): stride 2, the same grid as `pf_random_at`/`pf_random_bits_at`** --
    draw `d` is words `2d-2` and `2d-1`, i.e. block `(d-1)//2` pair `(d-1)%2`.

    So the documented "the three 64-bit generics are one grid at one coordinate" property is now
    RANGE-DEPENDENT: it holds for a wide range, and for a narrow one the integer draw shares its
    grid with `pf_random32_at` instead.  The advice that follows is unchanged -- take two generics
    at different draws, or on different streams -- but which generic a narrow integer draw collides
    with has moved.  Under `/v1` this generic had stride 4; `/v2` aligned it to stride 2 and then
    admitted this narrow rule.  Returns (value, retries).
    """
    if lo > hi:
        lo, hi = hi, lo
    a, s = lo, u64(hi - lo + 1)
    d = clamp_draw(draw)
    if s == 0:                                    # the full int64 range: nothing to reduce
        return signed64(bits_at(seed, stream, d)), 0
    if 1 <= s <= NARROW32_CAP:                    # the 32-bit grid
        threshold = (1 << 32) % s
        blk, slot = (d - 1) // 4, (d - 1) % 4
        attempt = 0
        while True:                               # uncapped: a cap would reintroduce bias
            key = None if attempt == 0 else retry_key(seed, attempt)
            x = block(seed, stream, blk, key=key)[slot]
            product = x * s
            if (product & M32) >= threshold:
                return a + (product >> 32), attempt
            attempt += 1
    blk, pair = (d - 1) // 2, (d - 1) % 2
    threshold = umod_2p64(s)
    attempt = 0
    while True:                                   # uncapped: a cap would reintroduce bias
        key = None if attempt == 0 else retry_key(seed, attempt)
        c = block(seed, stream, blk, key=key)
        x = (c[2 * pair + 1] << 32) | c[2 * pair]
        product = x * s
        if (product & MASK64) >= threshold:
            return a + (product >> 64), attempt
        attempt += 1


def fill_at(seed, stream, count, draw=1):
    return [at(seed, stream, draw + k) for k in range(count)]


def fill_at32(seed, stream, count, draw=1):
    return [at32(seed, stream, draw + k) for k in range(count)]


