# writer_guard_sequential_handoff is the negative control for the two racy
# scenarios: it expects exit 0 (no abort) rather than an abort, and it too is
# only meaningful with a real OpenMP flag -- with one thread both halves of the
# hand-off run on the same thread, where the guard admits re-entry by design.
#
# concurrent_calls_into_shared_reader/writer are deliberately not in the list
# above: they only reliably trigger under genuine multi-threaded execution (a
# real OpenMP flag supplied via FPM_FFLAGS -- see README's "Thread safety"
# section), which this script does not assume. When OpenMP is not active the
# scenarios detect that (omp_get_max_threads() <= 1) and skip cleanly. They are
# run separately below, sequentially (not part of the parallel batch -- they
# specifically probe OpenMP thread contention, and running them alongside a
# pool of other concurrent processes would only add timing noise), and do not
# count towards failures whether they abort (guard fired) or skip (no real
# concurrency available).
# table_first_touch_in_parallel and table_resolve_width_in_parallel join them
# for the same reason: without a real OpenMP flag there is no parallel region
# for the RF4 guard to notice, so the scenario simply reads the column and
# exits 0.
#
# table_first_touch_in_parallel_single/table_resolve_width_in_parallel_single
# are the deterministic (single-touching-thread, via !$omp single) siblings of
# the two above: they still need a real OpenMP flag for their team of 2 to be
# an "active" parallel region at all (same skip-and-exit-0 fallback otherwise),
# so they belong in this same best-effort bucket rather than the strict,
# exact-stderr-checked list above -- but unlike their racy siblings they do
# not depend on two threads racing into error stop's abort machinery at once,
# so they are what actually cover table_touch's/table_resolve_width's guard
# body lines (parquet_tables_read.f90) reliably under a real -fopenmp build.
#
# The five table_*_shared_in_parallel / table_set_null_no_validity_in_parallel
# scenarios are milestone 3d's own guards, and belong in this bucket for
# exactly the same reason: each opens a table OUTSIDE a parallel region and
# then changes it inside one, which is only detectable when there is a real
# region to be inside. Without an OpenMP flag the change simply succeeds and
# the scenario exits 0. All five use !$omp single, so exactly one thread runs
# the abort -- they are deterministic when OpenMP is active, unlike the two
# racy scenarios above. Because they ARE deterministic under a real -fopenmp
# build, `table_reserve_columns_shared_in_parallel` additionally keeps a strict
# test-drive wrapper (`test_table_reserve_columns_shared_aborts`,
# test/test_errors.f90) that asserts the exact abort and skips itself without
# OpenMP -- so moving it out of the strict list here costs no coverage on any
# build that can actually run it. It had been in the strict list alone among
# the five, which is why a no-OpenMP build (flang) reported it as a failure.
