def self_test():
    """Re-derive every published anchor.  Returns a list of failure descriptions."""
    bad = []

    def eq(label, got, want):
        if got != want:
            bad.append("%-52s got %s  want %s" % (label, got, want))

    for n, (ctr, key, out) in enumerate(KAT, start=1):
        eq("Random123 KAT %d" % n, philox4x32_10(*ctr, *key), out)

    checksum = 0
    for n in range(1, 200001):
        checksum ^= mix64(n * 2654435761)
    eq("mix64 xor checksum n=1..200000", signed64(checksum), MIX64_CHECKSUM)
    eq("mix64(0)", mix64(0), 0)
    eq("pf_random_key(0, 0)", random_key(0, 0), 0)

    eq("int_at(12345,1,0,huge) wide-width anchor", int_at(12345, 1, 0, INT64_MAX)[0],
       WIDE_WIDTH_ANCHOR)

    for seed, stream, want_bits, want_at in ANCHOR_SCALAR:
        eq("bits_at(%d,%d)" % (seed, stream), signed64(bits_at(seed, stream)), want_bits)
        eq("at(%d,%d)" % (seed, stream), "%.17f" % at(seed, stream), "%.17f" % want_at)

    for seed, stream, lo, hi, want in ANCHOR_INT:
        value, retries = int_at(seed, stream, lo, hi)
        eq("int_at(%d,%d,%d,%d)" % (seed, stream, lo, hi), value, want)
        # For a narrow range, check the SAME value a second time from the written specification.
        # Six of these anchors were re-baselined when the narrow grid was admitted, so without an
        # independently written path they would only be checking the oracle against itself.
        w = u64(max(lo, hi) - min(lo, hi) + 1)
        if 1 <= w <= NARROW32_CAP:
            eq("int_at(%d,%d,%d,%d) from spec" % (seed, stream, lo, hi),
               check_narrow_from_spec(seed, stream, lo, hi), want)
        else:
            eq("int_at(%d,%d,%d,%d) from spec" % (seed, stream, lo, hi),
               check_wide_from_spec(seed, stream, lo, hi), want)
        if retries:
            bad.append("int_at(%d,%d,%d,%d) retried %d times -- it is not a stable anchor and "
                       "must be removed from ANCHOR_INT" % (seed, stream, lo, hi, retries))

    for seed, label, want in ANCHOR_KEY:
        eq("pf_random_key(%d,%d)" % (seed, label), signed64(random_key(seed, label)), want)

    # Contract identities, asserted here as well as in the suite: a break in any of them would
    # otherwise reach the emitted table as a consistent pair of wrong values.
    # The full-range draw is NOT `bits_at` any more -- see int_at.  What is still contract is that
    # it needs no reduction, so it must equal the wide-space pair read straight, which is exactly
    # what the independently written `check_wide_from_spec` computes.
    eq("width-0 int_at from spec", int_at(12345, 1, INT64_MIN, INT64_MAX)[0],
       check_wide_from_spec(12345, 1, INT64_MIN, INT64_MAX))
    if int_at(12345, 1, INT64_MIN, INT64_MAX)[0] == signed64(bits_at(12345, 1)):
        bad.append("width-0 int_at still equals bits_at: the integer space is not separated")
    eq("lo>hi swaps", int_at(12345, 1, 999999, 0)[0], int_at(12345, 1, 0, 999999)[0])
    eq("draw 0 clamps to 1", bits_at(12345, 1, 0), bits_at(12345, 1, 1))
    eq("draw -5 clamps to 1", bits_at(12345, 1, -5), bits_at(12345, 1, 1))
    eq("at == to_real64(bits_at)", at(12345, 7, 3), float(bits_at(12345, 7, 3) >> 11) * 2.0**-53)
    eq("fill prefix consistency", fill_at(12345, 1, 3), fill_at(12345, 1, 6)[:3])
    eq("fill offset start", fill_at(12345, 1, 3, draw=4), fill_at(12345, 1, 6)[3:])
    eq("fill agrees with scalar", fill_at(12345, 1, 1), [at(12345, 1)])
    eq("fill32 agrees with scalar", fill_at32(12345, 1, 1), [at32(12345, 1)])

    # The two real64 values of one block must come from that block's two pairs -- the property
    # the superseded mapping broke, restated so a regression cannot pass quietly.
    c = block(12345, 1, 0)
    eq("draw 1 is pair (c0,c1)", bits_at(12345, 1, 1), (c[1] << 32) | c[0])
    eq("draw 2 is pair (c2,c3)", bits_at(12345, 1, 2), (c[3] << 32) | c[2])

    # `/v3`: the integer generic reads its OWN word space, so it shares bits with nothing.
    # Asserted at every draw rather than only draw 1, because a draw-1-only check would pass
    # against a build that had tagged the scalar path and forgotten the fills.
    for d in (1, 2, 3, 4, 5, 8, 9):
        eq("int_at at draw %d from spec" % d,
           int_at(12345, 1, INT64_MIN, INT64_MAX, d)[0],
           check_wide_from_spec(12345, 1, INT64_MIN, INT64_MAX, draw=d))
    # Negative control, and it is the one that matters: the integer draw must NOT be any of the
    # 64-bit real draws.  Without it, a build that dropped every domain tag would satisfy the
    # `from spec` checks above -- both paths would simply be wrong together.
    for d in (1, 2, 3, 4, 5, 8, 9):
        got = int_at(12345, 1, INT64_MIN, INT64_MAX, d)[0]
        for e in (d, 2 * d - 1, 2 * d):
            if got == signed64(bits_at(12345, 1, e)):
                bad.append("int_at at draw %d equals bits_at at draw %d -- the integer and real64 "
                           "word spaces are not separated" % (d, e))
    # And the same for the narrow grid against real32, which shares its stride.
    for d in (1, 2, 3, 5):
        if int_at(12345, 1, 0, 999, d)[0] == 0 + (word(12345, 1, d - 1) * 1000 >> 32):
            bad.append("narrow int_at at draw %d is a reduction of pf_random32_at's own word -- "
                       "the integer and real32 word spaces are not separated" % d)
    # Two consecutive integer draws must share one block, which is what the bulk fill amortises.
    eq("int draws 1 and 2 share block 0", ((1 - 1) // 2, (2 - 1) // 2), (0, 0))

    # ---- the exponential ---------------------------------------------------------------------
    #
    # The frozen transform is checked against the arbitrary-precision logarithm rather than
    # against itself: `exp_key_oracle` is a re-derivation, so agreeing with the Fortran proves
    # only that two implementations of the same recipe agree. What makes the recipe RIGHT is that
    # it lands within a couple of ulp of `decimal`'s `ln`, which knows nothing about it.
    worst = 0.0
    for e in range(-52, 1):                     # every binade a `1 - u` can occupy
        for frac in (0.0, 0.3, 0.5, 0.7, 0.999999):
            u = math.ldexp(1.0 + frac, e - 1)
            if not (2.0 ** -53 <= u <= 1.0):
                continue
            got, want = exp_key_oracle(u), neg_log_reference(u)
            if want != 0.0:
                ulp = abs(got - want) / math.ulp(want)
                worst = max(worst, ulp)
    if worst > 2.5:
        bad.append("exp_key_oracle is %.2f ulp from the arbitrary-precision log (want <= 2.5) -- "
                   "the re-derivation does not match the transform it models" % worst)

    # The `1 - u` convention, which is what stops a draw being infinite. `u` can be exactly 0
    # (probability 2**-53) and can never be 1, so `-log(u)` would be infinite and `-log(1-u)` is
    # finite always. Asserted on the constants rather than on a coordinate, since no coordinate
    # in this grid reaches either endpoint.
    eq("u = 0 gives a finite draw", exp_key_oracle(1.0 - 0.0), 0.0)
    eq("the largest draw is -log(2**-53)", "%.10f" % exp_key_oracle(2.0 ** -53), "36.7368005697")
    if not math.isinf(neg_log_reference(0.0)):
        bad.append("exp_reference(1.0) is finite -- the `1 - u` convention is what keeps a draw "
                   "finite, and a grid reaching u = 1 would have to be refused, not rounded")

    # The exponential reads the SAME uniform as `pf_random_at` at that coordinate. Without this
    # the two tables could drift onto different draw mappings and each stay self-consistent.
    for d in (1, 2, 3, 5):
        eq("exp at draw %d transforms at() at draw %d" % (d, d),
           exp_portable_at(12345, 1, d), exp_key_oracle(1.0 - at(12345, 1, d)))

    # ---- the normal ----------------------------------------------------------------------------
    #
    # The oracle is checked against the DISTRIBUTION rather than against a second implementation,
    # because there is no second implementation to check it against. A transcription error in the
    # ziggurat walk almost always shows up in the fourth moment even when the first two survive.
    for label, fn in (("ziggurat", normal_at), ("polar", normal_portable_at)):
        n = 40000
        vals = [fn(4242, 1, d)[0] for d in range(1, n + 1)]
        mean = sum(vals) / n
        var = sum(x * x for x in vals) / n - mean * mean
        kurt = sum(x ** 4 for x in vals) / n
        if abs(mean) > 4.0 / math.sqrt(n):
            bad.append("%s oracle mean %.5f is more than 4 SE from 0" % (label, mean))
        if abs(var - 1.0) > 5.0 * math.sqrt(2.0 / n):
            bad.append("%s oracle variance %.5f is more than 5 SE from 1" % (label, var))
        if abs(kurt - 3.0) > 6.0 * math.sqrt(96.0 / n):
            bad.append("%s oracle kurtosis %.5f is more than 6 SE from 3 -- the tails are wrong, "
                       "which is what a mis-walked ziggurat looks like when the first two moments "
                       "survive" % (label, kurt))

    # Risk-2: the two realisations must not read the same words at the same coordinate. Asserted
    # STRUCTURALLY -- the two sub-keys, and hence the first word pair each one reads, must differ --
    # because a statistical test cannot see this coupling at all.
    #
    # **That is measured, not assumed, and it is the interesting part.** Running both realisations
    # over the SAME sub-key (a deliberate coupling: they then transform the very same 64 bits) and
    # correlating 40000 pairs gives r = -0.00005, which is 0.01 standard errors from zero. A
    # correlation test would pass the broken construction as confidently as the correct one. The
    # reason is that the two algorithms extract different functions of the same bits -- the
    # Ziggurat's sign is bit 8 and the polar's is bit 63 of the same word, so even the signs are
    # independent -- and linear correlation is blind to that kind of dependence. Risk-2's own
    # measured instance was likewise invisible to every marginal test and showed up only as a 66 %
    # agreement in one rare joint cell.
    #
    # So the check that has power here is the exact one. The Fortran suite carries the joint-cell
    # statistic (`test_normal_realisations_independent`), which does have power, together with a
    # deliberately coupled control arm to prove it.
    for d in (1, 2, 3, 17, 1000):
        kz = random_key(random_key(4242, NORMAL_ZIG_LABEL), d)
        kp = random_key(random_key(4242, NORMAL_POLAR_LABEL), d)
        eq("normal sub-keys differ at draw %d" % d, kz == kp, False)
        eq("normal first word pairs differ at draw %d" % d,
           bits_at(kz, 1, 1) == bits_at(kp, 1, 1), False)

    eq("the two normal labels differ", NORMAL_ZIG_LABEL == NORMAL_POLAR_LABEL, False)

    # Consumption shape, which is contract for the stream walk.
    for d in range(1, 400):
        _, pp = normal_portable_at(12345, 1, d)
        if pp % 2 != 0 or pp < 2:
            bad.append("polar consumed %d pairs at draw %d -- it reads two uniforms per candidate, "
                       "so the count must be even and at least 2" % (pp, d))
            break

    # ---- The row sample's label, cross-checked against the SOURCE ----
    #
    # SAMPLE_LABEL is a copy of a value that lives in src/parquet_core.f90, and a copy is exactly
    # what goes stale. Read the declaration back rather than trusting the constant above: without
    # this, changing the label in Fortran and forgetting the oracle regenerates a whole table of
    # plausible, wrong uniforms, and the suite then fails against vectors nobody can explain.
    # Skipped rather than failed when the source is absent, so the generator still runs standalone.
    core = pathlib.Path(__file__).resolve().parent.parent / "src" / "parquet_core.f90"
    if core.exists():
        m = re.search(r"parquet_sample_label\s*=\s*(-?\d+)_int64", core.read_text())
        if m is None:
            bad.append("src/parquet_core.f90 declares no parquet_sample_label -- the oracle's "
                       "SAMPLE_LABEL cannot be checked against the source")
        else:
            eq("SAMPLE_LABEL matches src/parquet_core.f90", SAMPLE_LABEL, int(m.group(1)))
    eq("the sample label differs from the normal labels",
       SAMPLE_LABEL in (NORMAL_ZIG_LABEL, NORMAL_POLAR_LABEL, 0), False)

    # ---- Points on a sphere ------------------------------------------------------------------
    #
    # The labels, cross-checked against the SOURCE for the reason SAMPLE_LABEL is, and required to
    # be distinct from each other, from 0 and from every other label this oracle knows: two families
    # sharing a label would be two functions of one pair of uniforms (Risk-2).
    random_src = pathlib.Path(__file__).resolve().parent.parent / "src" / "parquet_random.f90"
    if random_src.exists():
        text = random_src.read_text()
        for name, value in SPHERE_LABELS.items():
            m = re.search(r"sphere_%s_label\s*=\s*(-?\d+)_int64" % name, text)
            if m is None:
                bad.append("src/parquet_random.f90 declares no sphere_%s_label" % name)
            else:
                eq("SPHERE_LABELS[%s] matches src/parquet_random.f90" % name, value, int(m.group(1)))
        declared = set(re.findall(r"sphere_(\w+?)_label\s*=", text))
        eq("every sphere label in the source is modelled", declared, set(SPHERE_LABELS))
    labels = list(SPHERE_LABELS.values())
    eq("the sphere labels are distinct", len(set(labels)), len(labels))
    eq("no sphere label is 0 or another family's",
       bool(set(labels) & {0, NORMAL_ZIG_LABEL, NORMAL_POLAR_LABEL, SAMPLE_LABEL}), False)

    # The decimal trigonometry, against values it cannot fake: exact angles and the Pythagorean
    # identity at 58 digits. A transcription error in a series or a quadrant shows up here first.
    D = decimal.Decimal
    close = D("1e-58")
    with dctx():
        checks = [
            ("sin(pi/6) = 1/2", dsin_cos(DPI / 6)[0], D("0.5")),
            ("cos(pi/3) = 1/2", dsin_cos(DPI / 3)[1], D("0.5")),
            ("sin(pi/2) = 1", dsin_cos(DPI / 2)[0], D(1)),
            ("cos(pi) = -1", dsin_cos(DPI)[1], D(-1)),
            ("sin(7*pi/6) = -1/2", dsin_cos(7 * DPI / 6)[0], D("-0.5")),
            ("cos(-2*pi/3) = -1/2", dsin_cos(-2 * DPI / 3)[1], D("-0.5")),
            ("atan(sqrt(3)) = pi/3", datan(D(3).sqrt()), DPI / 3),
            ("atan2(1, -1) = 3*pi/4", datan2(D(1), D(-1)), 3 * DPI / 4),
            ("atan2(-1, -1) = -3*pi/4", datan2(D(-1), D(-1)), -3 * DPI / 4),
            ("atan2(0, -1) = pi", datan2(D(0), D(-1)), DPI),
            ("atan2(-2, 0) = -pi/2", datan2(D(-2), D(0)), -DPI / 2),
        ]
        for label, got, want in checks:
            if abs(got - want) > close:
                bad.append("sphere model: %s is off by %s" % (label, abs(got - want)))
        # The vMF offset at the two ends of kappa: 2*u in the uniform limit to within kappa itself,
        # and the plain formula where nothing cancels.
        for kappa in ("1e-300", "1e-40"):
            if abs(d_vmf_h(float(kappa), 0.25) - D("0.5")) > D(kappa):
                bad.append("sphere model: the vMF offset at kappa %s is not 2*u" % kappa)
        plain = -((1 - D("0.25")) + D("0.25") * (D(-4)).exp()).ln() / 2
        if abs(d_vmf_h(2.0, 0.25) - plain) > close:
            bad.append("sphere model: the vMF offset at kappa 2 is not the plain inverse CDF")
        for x in ("0.1", "1", "2.5", "4", "6.2", "-3"):
            s, c = dsin_cos(D(x))
            if abs(s * s + c * c - 1) > close:
                bad.append("sphere model: sin^2 + cos^2 is not 1 at %s" % x)
            # The half-angle form the library uses must be the same number as 1 - cos.
            hs, _ = dsin_cos(D(x) / 2)
            if abs(2 * hs * hs - (1 - c)) > close:
                bad.append("sphere model: 2*sin(x/2)**2 is not 1 - cos(x) at %s" % x)

    # The block mapping: the two uniforms are the halves of block draw-1 of the derived key, i.e.
    # pf_random_at at draws 2d-1 and 2d -- and the second label is read at (key, stream, draw).
    for d in (1, 2, 5, 1000):
        key = random_key(0, SPHERE_LABELS["direction"])
        eq("direction uniforms at draw %d are at(key, 0, 2d-1) and at(key, 0, 2d)" % d,
           sphere_pair(0, SPHERE_LABELS["direction"], 0, d), (at(key, 0, 2 * d - 1), at(key, 0, 2 * d)))
    top = block(random_key(12345, SPHERE_LABELS["disc"]), 1, SPHERE_DRAW_MAX - 1)
    eq("draw 2**62 reads block 2**62 - 1 of the REAL64 space",
       sphere_pair(12345, SPHERE_LABELS["disc"], 1, SPHERE_DRAW_MAX)[0],
       float(((top[1] << 32) | top[0]) >> 11) * 2.0 ** -53)
    eq("block 2**62 - 1 leaves the domain bits clear", (SPHERE_DRAW_MAX - 1) >> 62, 0)

    # The model's own distributions, cheaply: an isotropic mean, a disc that stays inside itself,
    # the vMF's mean resultant length, and an orthonormal rotation.
    n = 3000
    zsum = D(0)
    for d in range(1, n + 1):
        zsum += sphere_direction(4242, 3, d)[0][2]
    if abs(float(zsum) / n) > 4.0 / math.sqrt(3 * n):
        bad.append("sphere model: the mean z of %d directions is more than 4 SE from 0" % n)
    cap = 1 - dsin_cos(D("0.5"))[1]
    for d in range(1, 200):
        h = sphere_disc(4242, 3, d, (0.0, 0.0, 1.0), 0.5, 0.0)[3]
        if not (0 <= h <= cap):
            bad.append("sphere model: a disc of radius 0.5 placed a point at h = %s" % h)
            break
    wsum = D(0)
    for d in range(1, n + 1):
        wsum += 1 - sphere_vmf(4242, 3, d, (0.0, 0.0, 1.0), 50.0)[3]
    want_w = (math.cosh(50.0) / math.sinh(50.0)) - 1.0 / 50.0
    if abs(float(wsum) / n - want_w) > 6.0 * math.sqrt((1 - want_w * want_w) / n):
        bad.append("sphere model: the vMF mean resultant at kappa 50 is %.5f, want %.5f"
                   % (float(wsum) / n, want_w))
    for d in (1, 2, 3):
        r = sphere_rotation(4242, 3, d)[0]
        with dctx():
            worst = max(abs(sum(r[i][k] * r[j][k] for k in range(3)) - (1 if i == j else 0))
                        for i in range(3) for j in range(3))
        if worst > close:
            bad.append("sphere model: rotation %d is not orthonormal (%s)" % (d, worst))

    # The emitted form of a real is its exact bit pattern: a round trip loses nothing.
    for x in (0.1, -2.5e-300, math.pi, 1.0 - 2.0 ** -53):
        back = struct.unpack("<d", struct.pack("<q", int(bits64(x).split("_")[0].strip("()"))))[0] \
            if not bits64(x).startswith("(") else None
        if back is not None and back != x:
            bad.append("sphere emission: %r does not survive its bit pattern" % x)

    return bad


