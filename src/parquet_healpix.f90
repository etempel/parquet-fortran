    ! ---- Interfaces: scheme conversion ----
    !
    ! Implemented in submodule parquet_healpix_core.

    interface
        !> RING -> NEST, int32 kinds. See the `pf_ring2nest` generic.
        pure elemental module subroutine hpx_ring2nest_i32(nside, ipring, ipnest)
