WIDTH = 128           # emitted lines stay inside the project's 132-column limit


def int_literal(value, kind):
    """A Fortran literal for `value`.  The extreme negative of a kind cannot be written directly:
    `-9223372036854775808_int64` is parsed as the negation of a constant that does not fit, which
    is a compile error, so it is built from `huge` instead (the same trap as `-128_int8`)."""
    limits = {"int64": INT64_MIN, "int32": -(1 << 31)}
    if value == limits[kind]:
        return "(-huge(1_%s) - 1_%s)" % (kind, kind)
    return "%d_%s" % (value, kind)


def real_literal(value, kind):
    """Shortest round-tripping decimal, with an explicit kind so no literal is default-real."""
    text = repr(value)
    if "e" in text or "E" in text:
        mantissa, _, exponent = text.partition("e")
        if "." not in mantissa:
            mantissa += ".0"
        return "%s_%s * 10.0_%s**(%d)" % (mantissa, kind, kind, int(exponent))
    if "." not in text:
        text += ".0"
    return "%s_%s" % (text, kind)


def array(decl, name, size_expr, items, indent=4):
    """Emit `decl :: name(size_expr) = [ ... ]`, wrapped with '&' continuations."""
    pad = " " * indent
    body = " " * (indent + 4)
    out = ["%s%s, parameter :: %s(%s) = [ &" % (pad, decl, name, size_expr)]
    line = body
    for n, item in enumerate(items):
        piece = item + (", " if n < len(items) - 1 else "]")
        if line.rstrip() != body.rstrip() and len(line) + len(piece) + 2 > WIDTH:
            out.append(line.rstrip() + " &")
            line = body
        line += piece
    out.append(line.rstrip())
    return out


def comment_block(text, indent=4):
    return ["%s!! %s" % (" " * indent, line) if line else "%s!!" % (" " * indent)
            for line in text.split("\n")]


