def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="compare the committed file with a fresh generation; exit 1 on drift")
    ap.add_argument("--self-test", action="store_true",
                    help="re-derive every published anchor; exit 1 if any of them fails")
    args = ap.parse_args()

    if args.self_test:
        bad = self_test()
        if bad:
            print("generate_random_golden_vectors.py: %d published anchor(s) NOT reproduced:"
                  % len(bad), file=sys.stderr)
            for line in bad:
                print("  " + line, file=sys.stderr)
            print("The oracle does not implement the contract. Do NOT regenerate from it.",
                  file=sys.stderr)
            return 1
        print("generate_random_golden_vectors.py: self-test OK "
              "(%d KATs, the mix64 checksum, %d scalar, %d integer and %d key anchors, "
              "plus the contract identities)."
              % (len(KAT), len(ANCHOR_SCALAR), len(ANCHOR_INT), len(ANCHOR_KEY)))
        return 0

    text = gen_module()

    over = [n for n, line in enumerate(text.split("\n"), start=1) if len(line) > 132]
    if over:
        print("generate_random_golden_vectors.py: emitted line(s) exceed 132 columns: %s"
              % over[:10], file=sys.stderr)
        return 1

    if args.check:
        if not OUT_PATH.exists() or OUT_PATH.read_text() != text:
            print("generate_random_golden_vectors.py --check: %s differs from a fresh generation."
                  % OUT_PATH.relative_to(REPO_ROOT), file=sys.stderr)
            print("Re-run tools/generate_random_golden_vectors.py to regenerate.", file=sys.stderr)
            return 1
        print("generate_random_golden_vectors.py --check: %s is current."
              % OUT_PATH.relative_to(REPO_ROOT))
        return 0

    OUT_PATH.write_text(text)
    print("generate_random_golden_vectors.py: wrote %s (%d lines)."
          % (OUT_PATH.relative_to(REPO_ROOT), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
