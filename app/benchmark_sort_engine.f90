    ! Small helpers
    ! ================================================================================

    !> Wall-clock seconds. `omp_get_wtime` where OpenMP is available; `system_clock` otherwise, so
    !! the serial arms still measure something on a toolchain without an `omp_lib` module.
    function wtime() result(t)
        real(real64) :: t !! seconds since an arbitrary origin.
#ifndef _OPENMP
        integer(int64) :: c, r
#endif
        !
#ifdef _OPENMP
        t = omp_get_wtime()
#else
        call system_clock(count=c, count_rate=r)
        t = real(c, real64) / real(r, real64)
#endif
    end function wtime

    !> The high thread count for this run.
    function thi() result(t)
        integer :: t !! threads.
        !
        if (threads_hi > 0) then
            t = threads_hi
        else
#ifdef _OPENMP
            t = omp_get_max_threads()
#else
            t = 1
#endif
        end if
    end function thi

    !> The thread ladder for `--mode=threads`: 1, then doubling to the machine's maximum, with the
    !! maximum itself always included.
    function thread_ladder() result(tl)
        integer, allocatable :: tl(:) !! the ladder, ascending.
        integer :: t, m, k
        integer :: tmp(32)
        !
        m = thi()
        k = 0
        t = 1
        do while (t < m .and. k < 31)
            k = k + 1
            tmp(k) = t
            t = t * 2
        end do
        k = k + 1
        tmp(k) = m
        tl = tmp(1:k)
    end function thread_ladder

    !> Rounds for one size: the full count at small n, falling to 1 at the top of the ladder, so a
    !! sweep does not spend an hour on its largest row. The count is REPORTED in every row, because
    !! a best-of-1 figure and a best-of-20 figure are not the same kind of number.
    function reps(n) result(r)
        integer(int64), intent(in) :: n !! rows.
        integer(int64) :: r             !! rounds to run.
        !
        r = max(1_int64, min(int(rounds, int64), 20000000_int64 / max(n, 1_int64) + 1_int64))
    end function reps

    !> xorshift64. Bit operations only, so it cannot overflow and is bit-identical on every
    !! compiler -- which is what makes a gfortran figure and an ifx figure comparable at all.
    function next_u63(st) result(v)
        integer(int64), intent(inout) :: st !! generator state; must start nonzero.
        integer(int64) :: v                 !! a non-negative pseudo-random integer.
        !
        st = ieor(st, ishft(st, 13))
        st = ieor(st, ishft(st, -7))
        st = ieor(st, ishft(st, 17))
        v = iand(st, huge(1_int64))
    end function next_u63

    !> .true. when a distribution is meaningful for a family (NaN only for the real families).
    function dist_applies(fam, dst) result(ok)
        character(len=*), intent(in) :: fam !! key family.
        character(len=*), intent(in) :: dst !! distribution name.
        logical :: ok                       !! .true. when the pair is worth running.
        !
        ok = .true.
        if (dst == "nan") ok = (fam == "f32" .or. fam == "f64")
    end function dist_applies

    !> Number of comma-separated items in a list.
    function list_len(s) result(k)
        character(len=*), intent(in) :: s !! the comma-separated list.
        integer :: k                      !! how many items it holds.
        integer :: i
        !
        k = 1
        do i = 1, len_trim(s)
            if (s(i:i) == ",") k = k + 1
        end do
    end function list_len

    !> Item `k` of a comma-separated list.
    function list_item(s, k) result(item)
        character(len=*), intent(in) :: s        !! the comma-separated list.
        integer, intent(in) :: k                 !! 1-based item wanted.
        character(len=:), allocatable :: item    !! that item, trimmed.
        integer :: i, cur, lo
        !
        cur = 1
        lo = 1
        do i = 1, len_trim(s)
            if (s(i:i) == ",") then
                if (cur == k) then
                    item = trim(adjustl(s(lo:i - 1)))
                    return
                end if
                cur = cur + 1
                lo = i + 1
            end if
        end do
        item = trim(adjustl(s(lo:len_trim(s))))
    end function list_item

    !> An integer as a string, for banner text.
    function i2s(v) result(s)
        integer(int64), intent(in) :: v       !! the value.
        character(len=:), allocatable :: s    !! its decimal rendering.
        character(len=32) :: buf
        !
        write(buf,'(i0)') v
        s = trim(buf)
    end function i2s

    ! ================================================================================
    ! Argument parsing
    ! ================================================================================

    !> Parses `--key=value` arguments. Every parse failure is fatal rather than defaulted: a
    !! mistyped size that silently becomes zero produces a full page of plausible figures about
    !! nothing.
    subroutine parse_args()
        integer :: i, eq, ios, k
        character(len=256) :: arg
        character(len=:), allocatable :: key, val
        integer(int64) :: tmp(64)
        !
        mode = "all"
        families = "i32,i64,i64lo,f32,f64,str,multi2,multi3"
        dists = "rand,sorted,reverse,organ,equal,null001,null10,nan"
        thread_dist = "rand"
        sizes_arg = "1000,10000,100000,1000000,5000000,20000000"
        engine = "cpp"
        radix_min = -1_int64
        !
        do i = 1, command_argument_count()
            call get_command_argument(i, arg)
            if (trim(arg) == "--help" .or. trim(arg) == "-h") then
                call usage()
                stop 0
            end if
            eq = index(arg, "=")
            if (eq <= 0) cycle
            key = trim(arg(1:eq - 1))
            val = trim(arg(eq + 1:))
            ios = 0
            select case (key)
            case ("--mode");     mode = val
            case ("--families"); families = val
            case ("--dists");    dists = val
            case ("--thread-dist"); thread_dist = val
            case ("--sizes");    sizes_arg = val
            case ("--rounds");   read(val, *, iostat=ios) rounds
            case ("--perm");     read(val, *, iostat=ios) permkind
            case ("--strwidth"); read(val, *, iostat=ios) strwidth
            case ("--threads");  read(val, *, iostat=ios) threads_hi
            case ("--seed");     read(val, *, iostat=ios) seed_arg
            case ("--engine");   engine = val
            case ("--radix-min-rows"); read(val, *, iostat=ios) radix_min
            case ("--inner");    read(val, *, iostat=ios) inner
            case default
                write(error_unit,'(a)') "benchmark_sort_engine: unknown option '"//key//"'"
                call usage()
                error stop 2
            end select
            if (ios /= 0) then
                write(error_unit,'(a)') "benchmark_sort_engine: bad value for "//key//": '"//val//"'"
                error stop 2
            end if
        end do
        !
        if (engine /= "cpp" .and. engine /= "fortran") then
            write(error_unit,'(a)') "benchmark_sort_engine: --engine must be cpp or fortran"
            error stop 2
        end if
        ! Selecting the engine here rather than per arm: every arm below must run on ONE engine, or
        ! a figure could be filed against the wrong one with nothing in the output to say so.
        call parquet_debug_use_fortran_sort_engine(engine == "fortran")
        ! Same reasoning: set once, for every arm, so no figure can be filed against a floor
        ! other than the one the banner reports. Negative leaves the shipped floor alone.
        call parquet_debug_set_sort_radix_min_rows(radix_min)
        if (permkind /= 32 .and. permkind /= 64) then
            write(error_unit,'(a)') "benchmark_sort_engine: --perm must be 32 or 64"
            error stop 2
        end if
        if (rounds < 1) rounds = 1
        if (inner < 1) inner = 1
        if (seed_arg == 0_int64) seed_arg = 1_int64   ! xorshift64 is degenerate at zero
        !
        ! `read` needs a CHARACTER VARIABLE as its internal unit, never a function result, so the
        ! item is taken into a local first. gfortran rejects the direct form outright; a compiler
        ! that accepted it would be reading from a temporary.
        do k = 1, list_len(sizes_arg)
            val = list_item(sizes_arg, k)
            read(val, *, iostat=ios) tmp(k)
            if (ios /= 0 .or. tmp(k) < 2_int64) then
                write(error_unit,'(a)') "benchmark_sort_engine: bad size '"//val//"'"
                error stop 2
            end if
        end do
        sizes = tmp(1:list_len(sizes_arg))
    end subroutine parse_args

    !> Usage text.
    subroutine usage()
        write(output_unit,'(a)') "benchmark_sort_engine -- baseline harness for feature_sort.md"
