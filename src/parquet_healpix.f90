!> The HEALPix sphere pixelisation: position <-> pixel, scheme conversion, and disc queries.
!!
!! HEALPix divides the sphere into `12*nside**2` pixels of exactly equal area, arranged on rings of
!! constant latitude. `parquet_healpix` implements the part of it a program actually needs to hold
!! sky data on a grid: converting a direction to the pixel containing it and back, converting
!! between the two pixel-numbering schemes, and enumerating the pixels of a disc.
!!
!! **Written from the published algorithm, not translated from any implementation.** The
!! pixelisation is described completely in Gorski et al. 2005, ApJ 622, 759, and the geometry is
!! elementary; every formula here was derived from that paper and then checked against reference
!! vectors (`test/test_healpix_vectors.f90`, generated by `tools/generate_healpix_reference.py`).
!! No HEALPix source was consulted while writing this module, and none should be if it is ever
!! re-derived -- the paper plus the vectors are sufficient, and they are what keeps this library
!! BSD-3-Clause while `libhealpix` is GPL-2.0.
!!
!! **This module is Arrow-free by construction and that is the point of its tier.** It reaches
!! `iso_fortran_env`, `ieee_arithmetic` and `parquet_settings_base`, and nothing else, so
!! `use parquet_healpix` in a downstream project compiles four Fortran files rather than the
!! sixty-odd the reader/writer stack costs. `check_parquet_healpix_stays_arrow_free`
!! (tools/check_source_conventions.py) and `tools/module_footprints.txt` are what keep that true --
!! a `use` line added here can silently multiply what every consumer compiles, and no test can see
!! it happen.
!!
!! **No module state, no saved variables, no lazy initialisation.** Every procedure here is a
!! function of its arguments alone, so the whole module is thread-safe with nothing to arrange and
!! the scalar conversions are `pure elemental`. Do not add a cache: a `logical, save :: ready`
!! reached from inside a parallel region is a check-then-act on shared state.
!!
!! **Two conventions a caller must get right, and neither has a default this module can pick:**
!!
!! * `theta` is COLATITUDE from the north pole in radians, so `theta = pi/2 - dec`. A mirrored
!!   frame (`theta = pi/2 + dec`) is in live use in several projects that feed this module, and is
!!   self-consistent -- a reflection preserves angular distance -- but mixing the two searches the
!!   wrong hemisphere silently. This module takes HEALPix-native `theta`/`phi` and unit vectors
!!   only, and offers no RA/Dec layer, precisely so that the choice stays visible at each call.
!! * A pixel INDEX runs `0 .. 12*nside**2 - 1`, as the pixelisation itself defines it. The
!!   `listpix` array `pf_query_disc` fills is 1-based, like every other user-facing array in this
!!   library. The array base and the pixel base are different things and are the pair most easily
!!   conflated: `listpix(1)` holds the first pixel found, and its VALUE may well be 0.
module parquet_healpix
    use, intrinsic :: iso_fortran_env, only: int32, int64, real64
    use, intrinsic :: ieee_arithmetic, only: ieee_is_nan, ieee_is_finite
    use parquet_settings_base, only: parquet_set_verbosity, parquet_get_verbosity, &
        parquet_set_message_stream, parquet_get_message_stream
    implicit none
    private

    public :: PF_HP_RING, PF_HP_NEST
    public :: pf_ang2pix_ring, pf_ang2pix_nest
    public :: pf_pix2ang_ring, pf_pix2ang_nest
    public :: pf_pix2vec_ring, pf_pix2vec_nest
    public :: pf_ring2nest, pf_nest2ring
    public :: pf_query_disc
    public :: pf_angdist
    public :: pf_max_pixrad
    !
    ! ---- Settings this module's own code reads, re-exported so a narrow import can configure it ----
    !
    !> The output pair, because `pf_query_disc`'s bulk siblings emit a thread-clamp warning through
    !! the same channel every other tier does. Re-exported here so a program whose only import is
    !! `use parquet_healpix` can silence it without naming `parquet_settings` -- which would put the
    !! C++ boundary, and with it Arrow, back into an otherwise Arrow-free build.
    public :: parquet_set_verbosity, parquet_get_verbosity
    public :: parquet_set_message_stream, parquet_get_message_stream

    ! ---- Scheme selectors ----

    !> RING scheme: pixels numbered along rings of constant latitude, north to south.
    !!
    !! Index order follows latitude, which is what makes a declination band one contiguous range of
    !! indices. `pf_query_disc` returns RING results in ascending index order.
    integer, parameter :: PF_HP_RING = 0
    !> NEST scheme: pixels numbered so that the four children of a pixel at the next resolution are
    !! consecutive.
    !!
    !! A resolution change is a bit shift in this scheme, which is what makes it the right choice
    !! for hierarchical work. `pf_query_disc` does not promise any particular order for NEST output.
    integer, parameter :: PF_HP_NEST = 1

    ! ---- Kind and range limits ----

    !> Largest `nside` whose pixel indices still fit `integer(int32)`.
    !!
    !! `12*8192**2` is 805306368; the next power of two overflows a signed 32-bit index, so the
    !! int32 specifics refuse it rather than wrapping.
    integer(int64), parameter :: hpx_nside_max_i32 = 8192_int64
    !> Largest `nside` this module accepts at all, in either kind.
    !!
    !! `2**29` matches the ceiling the HEALPix ecosystem itself uses and keeps every intermediate
    !! inside `integer(int64)`: `npix` is `3*2**60`, the Morton interleave of two 29-bit
    !! coordinates occupies 58 bits, the face offset reaches `11*4**29 < 2**62`, and the cap-ring
    !! inversion's square-root argument stays below 7e18, where a double still resolves it to
    !! better than one part in a ring.
    integer(int64), parameter :: hpx_nside_max = 536870912_int64

    ! ---- Mathematical constants ----

    !> pi.
    real(real64), parameter :: hpx_pi = 3.141592653589793238462643_real64
    !> pi/2.
    real(real64), parameter :: hpx_halfpi = 0.5_real64 * hpx_pi
    !> 2*pi.
    real(real64), parameter :: hpx_twopi = 2.0_real64 * hpx_pi
    !> The |z| at which the polar caps meet the equatorial belt.
    real(real64), parameter :: hpx_twothird = 2.0_real64 / 3.0_real64

    ! ---- Morton-order bit masks ----
    !
    ! The NEST index interleaves the bits of a pixel's two within-face coordinates. Spreading and
    ! compacting them is done with the standard five-step mask sequence rather than a lookup table,
    ! which keeps the codec branch-free and -- more to the point here -- keeps the module free of
    ! any data at all, so there is nothing for a parallel region to share.

    !> Bit mask 0x00000000FFFFFFFF.
    integer(int64), parameter :: hpx_m32 = int(z'00000000FFFFFFFF', int64)
    !> Bit mask 0x0000FFFF0000FFFF.
    integer(int64), parameter :: hpx_m16 = int(z'0000FFFF0000FFFF', int64)
    !> Bit mask 0x00FF00FF00FF00FF.
    integer(int64), parameter :: hpx_m8 = int(z'00FF00FF00FF00FF', int64)
    !> Bit mask 0x0F0F0F0F0F0F0F0F.
    integer(int64), parameter :: hpx_m4 = int(z'0F0F0F0F0F0F0F0F', int64)
    !> Bit mask 0x3333333333333333.
    integer(int64), parameter :: hpx_m2 = int(z'3333333333333333', int64)
    !> Bit mask 0x5555555555555555 -- the even bit positions.
    integer(int64), parameter :: hpx_m1 = int(z'5555555555555555', int64)

    ! ---- Per-face ring and phi offsets ----
    !
    ! Faces 0-3 are the north cap, 4-7 the equatorial belt, 8-11 the south cap. These two tables
    ! place each face's centre on the (ring, index-in-ring) grid, and are what the NEST <-> RING
    ! conversions are built from.

    !> Ring offset of each face centre, in units of `nside`.
    integer(int64), parameter :: hpx_jrll(0:11) = [2_int64, 2_int64, 2_int64, 2_int64, &
        3_int64, 3_int64, 3_int64, 3_int64, 4_int64, 4_int64, 4_int64, 4_int64]
    !> Longitude offset of each face centre, in units of a ring's quarter width.
    integer(int64), parameter :: hpx_jpll(0:11) = [1_int64, 3_int64, 5_int64, 7_int64, &
        0_int64, 2_int64, 4_int64, 6_int64, 1_int64, 3_int64, 5_int64, 7_int64]

    ! ---- Public generic interfaces ----

    !> Pixel containing the direction `(theta, phi)`, in the RING scheme.
    !!
    !! `nside` is a positive power of two, `theta` is colatitude in radians (0 at the north pole,
    !! pi at the south), `phi` is longitude in radians and may lie outside `[0, 2*pi)`. `ipix`
    !! comes back in the same integer kind as `nside`, in `0 .. 12*nside**2 - 1`.
    !!
    !! **Total and `pure elemental`: it validates nothing and never aborts.** An `nside` that is
    !! not a positive power of two, or a `theta` outside `[0, pi]`, produces a meaningless result
    !! rather than an error -- `pf_ang2pix_ring(0, ...)` returns nonsense. That is deliberate: this
    !! is the per-element hot path, and validation belongs in the once-per-query entry points
    !! (`pf_query_disc`), which check `nside` once before their walk. A NaN angle propagates into
    !! the integer conversion, which may raise `IEEE_INVALID`; every OTHER path in this module is
    !! free of IEEE exceptions on validated input.
    interface pf_ang2pix_ring
        module procedure hpx_ang2pix_ring_i32
        module procedure hpx_ang2pix_ring_i64
    end interface pf_ang2pix_ring

    !> Pixel containing the direction `(theta, phi)`, in the NEST scheme.
    !!
    !! Arguments and kinds are `pf_ang2pix_ring`'s, and so is the total, non-validating contract:
    !! see that procedure for the full statement of both.
    interface pf_ang2pix_nest
        module procedure hpx_ang2pix_nest_i32
        module procedure hpx_ang2pix_nest_i64
    end interface pf_ang2pix_nest

    !> Direction of a RING pixel's centre, as `(theta, phi)` in radians.
    !!
    !! `ipix` is a RING index in `0 .. 12*nside**2 - 1`, in the same kind as `nside`. `theta` comes
    !! back in `[0, pi]` and `phi` in `[0, 2*pi)`.
    !!
    !! **Total and `pure elemental`, exactly as `pf_ang2pix_ring` is** -- an out-of-range `ipix`
    !! gives a meaningless answer rather than an abort.
    !!
    !! **Near the poles at very high resolution, `theta` carries fewer digits than `phi` does**, and
    !! that is inherent rather than a defect here: a ring's centre is defined by its `z`, and
    !! `theta = acos(z)` loses about half the significant digits when `z` is within an ulp or two of
    !! +-1. At `nside = 2**20` the first ring's `z` is `1 - 3e-13`, so `theta` is good to about
    !! 4e-10 rather than to an ulp. Work in `z`, or in unit vectors through `pf_pix2vec_ring`, when
    !! that matters.
    interface pf_pix2ang_ring
        module procedure hpx_pix2ang_ring_i32
        module procedure hpx_pix2ang_ring_i64
    end interface pf_pix2ang_ring

    !> Direction of a NEST pixel's centre, as `(theta, phi)` in radians.
    !!
    !! Arguments, kinds, contract and polar-precision caveat are `pf_pix2ang_ring`'s.
    interface pf_pix2ang_nest
        module procedure hpx_pix2ang_nest_i32
        module procedure hpx_pix2ang_nest_i64
    end interface pf_pix2ang_nest

    !> Unit vector of a RING pixel's centre.
    !!
    !! `vec` is the Cartesian direction `(x, y, z)` of the pixel centre. **This is the primitive
    !! form and `pf_pix2ang_ring` is derived from it**, not the other way round: the centre is
    !! built from the ring's `z` directly, with no `acos`/`cos` round trip. That is load-bearing
    !! rather than an optimisation -- a round trip moves a centre lying exactly on a disc's rim to
    !! the wrong side of it, which flips a whole equatorial ring in or out of a pole-centred
    !! hemisphere.
    !!
    !! Total and `pure`; not `elemental`, because the result is an array.
    interface pf_pix2vec_ring
        module procedure hpx_pix2vec_ring_i32
        module procedure hpx_pix2vec_ring_i64
    end interface pf_pix2vec_ring

    !> Unit vector of a NEST pixel's centre.
    !!
    !! Arguments, kinds and contract are `pf_pix2vec_ring`'s.
    interface pf_pix2vec_nest
        module procedure hpx_pix2vec_nest_i32
        module procedure hpx_pix2vec_nest_i64
    end interface pf_pix2vec_nest

    !> RING pixel index -> NEST pixel index, at the same `nside`.
    !!
    !! `ipring` and `ipnest` are both in `0 .. 12*nside**2 - 1` and in the same kind as `nside`.
    !! Exact integer arithmetic throughout -- no direction is computed and nothing rounds. Total
    !! and `pure elemental`, so an out-of-range input gives a meaningless answer rather than an
    !! abort.
    interface pf_ring2nest
        module procedure hpx_ring2nest_i32
        module procedure hpx_ring2nest_i64
    end interface pf_ring2nest

    !> NEST pixel index -> RING pixel index, at the same `nside`.
    !!
    !! The exact inverse of `pf_ring2nest`; same kinds, same total contract.
    interface pf_nest2ring
        module procedure hpx_nest2ring_i32
        module procedure hpx_nest2ring_i64
    end interface pf_nest2ring

    !> Largest angular distance from a pixel centre to one of its own corners, in radians.
    !!
    !! **The margin `pf_query_disc`'s `inclusive = .true.` mode enlarges its radius by, and the
    !! bound that mode publishes** -- so it is also the honest way to size a search margin around a
    !! position, where code of this kind often carries a rule-of-thumb factor instead.
    !!
    !! Attained on the first equatorial ring, whose pixels are the most elongated, at the corner
    !! lying on the quadrant meridian. `nside` takes either integer kind; the result is `real64`.
    !!
    !! `pure elemental` and total: it validates nothing, so an `nside` that is not a positive power
    !! of two gives a meaningless answer rather than an error, exactly as the conversions do.
    interface pf_max_pixrad
        module procedure hpx_max_pixrad_i32
        module procedure hpx_max_pixrad_i64
    end interface pf_max_pixrad

    !> Pixels of a disc: every pixel within `radius` of the direction `vec`.
    !!
    !! **The one entry point here that validates its arguments**, and the one that aborts. See
    !! `hpx_query_disc_i64` for the full contract: the two `inclusive` modes, the ordering promise
    !! (ascending for `PF_HP_RING`, unspecified for `PF_HP_NEST`), the 1-based `listpix` against
    !! 0-based pixel values, and every condition that stops the run.
    interface pf_query_disc
        module procedure hpx_query_disc_i32
        module procedure hpx_query_disc_i64
    end interface pf_query_disc

    ! ---- Interfaces: position <-> pixel ----
    !
    ! Implemented in submodule parquet_healpix_core.

    interface
        !> RING pixel for a direction, int32 kinds. See the `pf_ang2pix_ring` generic.
        pure elemental module subroutine hpx_ang2pix_ring_i32(nside, theta, phi, ipix)
            integer(int32), intent(in) :: nside !! resolution parameter, a positive power of two.
            real(real64), intent(in) :: theta !! colatitude from the north pole, radians.
            real(real64), intent(in) :: phi !! longitude, radians; any value is accepted.
            integer(int32), intent(out) :: ipix !! RING pixel index, 0-based.
        end subroutine hpx_ang2pix_ring_i32

        !> RING pixel for a direction, int64 kinds. See the `pf_ang2pix_ring` generic.
        pure elemental module subroutine hpx_ang2pix_ring_i64(nside, theta, phi, ipix)
            integer(int64), intent(in) :: nside !! resolution parameter, a positive power of two.
            real(real64), intent(in) :: theta !! colatitude from the north pole, radians.
            real(real64), intent(in) :: phi !! longitude, radians; any value is accepted.
            integer(int64), intent(out) :: ipix !! RING pixel index, 0-based.
        end subroutine hpx_ang2pix_ring_i64

        !> NEST pixel for a direction, int32 kinds. See the `pf_ang2pix_nest` generic.
        pure elemental module subroutine hpx_ang2pix_nest_i32(nside, theta, phi, ipix)
            integer(int32), intent(in) :: nside !! resolution parameter, a positive power of two.
            real(real64), intent(in) :: theta !! colatitude from the north pole, radians.
            real(real64), intent(in) :: phi !! longitude, radians; any value is accepted.
            integer(int32), intent(out) :: ipix !! NEST pixel index, 0-based.
        end subroutine hpx_ang2pix_nest_i32

        !> NEST pixel for a direction, int64 kinds. See the `pf_ang2pix_nest` generic.
        pure elemental module subroutine hpx_ang2pix_nest_i64(nside, theta, phi, ipix)
            integer(int64), intent(in) :: nside !! resolution parameter, a positive power of two.
            real(real64), intent(in) :: theta !! colatitude from the north pole, radians.
            real(real64), intent(in) :: phi !! longitude, radians; any value is accepted.
            integer(int64), intent(out) :: ipix !! NEST pixel index, 0-based.
        end subroutine hpx_ang2pix_nest_i64

        !> Centre direction of a RING pixel, int32 kinds. See the `pf_pix2ang_ring` generic.
        pure elemental module subroutine hpx_pix2ang_ring_i32(nside, ipix, theta, phi)
            integer(int32), intent(in) :: nside !! resolution parameter, a positive power of two.
            integer(int32), intent(in) :: ipix !! RING pixel index, 0-based.
            real(real64), intent(out) :: theta !! colatitude of the centre, radians, in [0, pi].
            real(real64), intent(out) :: phi !! longitude of the centre, radians, in [0, 2*pi).
        end subroutine hpx_pix2ang_ring_i32

        !> Centre direction of a RING pixel, int64 kinds. See the `pf_pix2ang_ring` generic.
        pure elemental module subroutine hpx_pix2ang_ring_i64(nside, ipix, theta, phi)
            integer(int64), intent(in) :: nside !! resolution parameter, a positive power of two.
            integer(int64), intent(in) :: ipix !! RING pixel index, 0-based.
            real(real64), intent(out) :: theta !! colatitude of the centre, radians, in [0, pi].
            real(real64), intent(out) :: phi !! longitude of the centre, radians, in [0, 2*pi).
        end subroutine hpx_pix2ang_ring_i64

        !> Centre direction of a NEST pixel, int32 kinds. See the `pf_pix2ang_nest` generic.
        pure elemental module subroutine hpx_pix2ang_nest_i32(nside, ipix, theta, phi)
            integer(int32), intent(in) :: nside !! resolution parameter, a positive power of two.
            integer(int32), intent(in) :: ipix !! NEST pixel index, 0-based.
            real(real64), intent(out) :: theta !! colatitude of the centre, radians, in [0, pi].
            real(real64), intent(out) :: phi !! longitude of the centre, radians, in [0, 2*pi).
        end subroutine hpx_pix2ang_nest_i32

        !> Centre direction of a NEST pixel, int64 kinds. See the `pf_pix2ang_nest` generic.
        pure elemental module subroutine hpx_pix2ang_nest_i64(nside, ipix, theta, phi)
            integer(int64), intent(in) :: nside !! resolution parameter, a positive power of two.
            integer(int64), intent(in) :: ipix !! NEST pixel index, 0-based.
            real(real64), intent(out) :: theta !! colatitude of the centre, radians, in [0, pi].
            real(real64), intent(out) :: phi !! longitude of the centre, radians, in [0, 2*pi).
        end subroutine hpx_pix2ang_nest_i64

        !> Centre unit vector of a RING pixel, int32 kinds. See the `pf_pix2vec_ring` generic.
        pure module subroutine hpx_pix2vec_ring_i32(nside, ipix, vec)
            integer(int32), intent(in) :: nside !! resolution parameter, a positive power of two.
            integer(int32), intent(in) :: ipix !! RING pixel index, 0-based.
            real(real64), intent(out) :: vec(3) !! unit vector of the pixel centre.
        end subroutine hpx_pix2vec_ring_i32

        !> Centre unit vector of a RING pixel, int64 kinds. See the `pf_pix2vec_ring` generic.
        pure module subroutine hpx_pix2vec_ring_i64(nside, ipix, vec)
            integer(int64), intent(in) :: nside !! resolution parameter, a positive power of two.
            integer(int64), intent(in) :: ipix !! RING pixel index, 0-based.
            real(real64), intent(out) :: vec(3) !! unit vector of the pixel centre.
        end subroutine hpx_pix2vec_ring_i64

        !> Centre unit vector of a NEST pixel, int32 kinds. See the `pf_pix2vec_nest` generic.
        pure module subroutine hpx_pix2vec_nest_i32(nside, ipix, vec)
            integer(int32), intent(in) :: nside !! resolution parameter, a positive power of two.
            integer(int32), intent(in) :: ipix !! NEST pixel index, 0-based.
