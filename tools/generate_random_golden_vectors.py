SEEDS = [0, 1, 12345, -7, INT64_MAX, INT64_MIN]
STREAMS = [-5, 0, 1, 2, 1000000]
DRAWS = [0, 1, 2, 5]                              # 0 exercises the clamp


def scalar_rows():
    """Every (seed, stream, draw) of the grid, with all three scalar draws' results."""
    rows = []
    for seed in SEEDS:
        for stream in STREAMS:
            for draw in DRAWS:
                rows.append((seed, stream, draw, signed64(bits_at(seed, stream, draw)),
                             at(seed, stream, draw), at32(seed, stream, draw)))
    return rows


